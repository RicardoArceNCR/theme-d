                <p>Castillo nunca pudo sentarse con sus padres para decirles que era gay. “Les dije que no me iba a casar, que era por un asunto personal y nunca se los iba a contar”, recuerda el abogado. Todo fue de golpe. </p>
                <p>Fue a mediados de los años 80 que Castillo rompe ataduras. Aunque sin militar públicamente, se une a movimientos de la diversidad sexual en Costa Rica. Al joven homosexual lo marcan los recuerdos del siglo anterior. “Los llevaban presos y los rapaban antes de soltarlos. También se invadieron bares gay y se cerraron. Para el año 85 con el auge del VIH, se volvieron a revivir las redadas”, afirma. </p>
                <p>Campos pertenece a una generación más joven, y al salir del clóset en la década del ochenta no sufrió tanto estigma, al menos de su entorno familiar.</p>
                <p>“Cuando mi familia se dio cuenta no trascendió mucho, porque me aceptaron y nunca se habló más del tema. En el caso de otras personas fue complejo por las redadas, el acoso. Yo no viví esa etapa pero recuerdo a amigos contar las persecuciones. No ha cambiado mucho porque, aunque existen leyes y normas, siguen habiendo casos de crímenes de odio, persecución y exclusión. No se ha cambiado el ideario colectivo y la mentalidad de la gente. Hasta que eso no suceda, seguiremos expuestos a la discriminación”, dice Campos. </p>
                <p>Hasta 1882, si las autoridades ticas sorprendían públicamente a una pareja del mismo sexo, podían llevarlos a la pena de muerte. Entonces, ese año, bajo la administración Guardia, se abolió la pena en todos sus extremos. Pero la homosexualidad quedó como un delito hasta 1970. Luego se convirtió en contravención llamada “sodomía” que terminaría por eliminarse del Código Penal en 2002.</p>
                <p>La lucha por el matrimonio igualitario inició con el siglo XXI en Costa Rica. En estos 20 años se presentaron cuatro proyectos de ley ante el Congreso, sin ningún éxito, y dos acciones de inconstitucionalidad ante el Alto Tribunal del país: la última fue la vencida.</p>
                <p>Finalmente Campos y Castillo presentaron una solicitud de matrimonio ante un Juzgado de Familia. Les dijeron que no, entonces apelaron y presentaron la acción de inconstitucionalidad ante la Sala Constitucional. La querella  fue resuelta en agosto de 2018.</p>
                <p>Alrededor del Alto Tribunal hubo gran expectativa ese día de agosto. Un pedazo de esperanza para la comunidad diversa del país, que ya había esperado demasiado. Pasaban las horas y los magistrados no se ponían de acuerdo. En la noche comenzaron a llegar personas a los edificios. Castillo y Campos no fueron, pues uno de ellos estaba resfriado. Esperaron la sentencia en casa.</p>
