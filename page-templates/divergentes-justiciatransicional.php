            <h1 class="mercenarios-armados">Cero impunidad</h1>
            <p>Los expertos consultados consideran que el nuevo gobierno debe buscar los cuatro principios que definen a
                la justicia: el reconocimiento de las violaciones de derechos humanos por parte del Estado, el acceso a
                la verdad, medidas de reparaci&oacute;n y ofrecer garant&iacute;as de que no se repitan, m&aacute;s all&aacute;
                de los modelos de justicia transicional, convencional o universal que decidan impulsar.&nbsp;</p>
            <p>Adem&aacute;s, se deben hacer reformas legales que permitan la conformaci&oacute;n de comisiones
                internacionales, como la Comisi&oacute;n de Internacional Contra la Impunidad en Guatemala (Cicig), y
                cuyo objetivo sea esclarecer la verdad y la judicializaci&oacute;n.&nbsp;</p>
            <p>Silvio Prado considera oportuno crear una instancia especial de judicializaci&oacute;n, que implique la
                creaci&oacute;n de tribunales especiales para que los responsables rindan cuentas. &ldquo;Esto nunca ha
                ocurrido en el pa&iacute;s, ni siquiera despu&eacute;s del derrocamiento de la dictadura somocista. Los
                tribunales anti somocistas no dieron garant&iacute;as a los acusados. Fueron mecanismos de
                <em>vendettas </em>pol&iacute;ticas y revanchas&rdquo;, dijo Prado. &ldquo;Si se ve desde la revancha
                pol&iacute;tica, este modelo se da&ntilde;&oacute;&rdquo;, advierte el analista.</p>
            <p>Ejemplos de justicia transicional existen varios y diversos en el mundo. Desde los acuerdos entre los
                guerrilleros colombianos y el gobierno, hasta la b&uacute;squeda de la verdad en los conflictos armados
                y de corrupci&oacute;n en El Salvador y Guatemala. &ldquo;Yo miro largo este proceso. Tiene que haber
                una cultura y visi&oacute;n distinta de la que existe ahora, incluso en el liderazgo de la oposici&oacute;n&rdquo;,
                dijo &Aacute;lvarez, quien considera a la justicia transicional como &ldquo;un instrumento que ofrece un
                gran valor para superar la crisis de 2018 y que sane las heridas&rdquo;.&nbsp;</p>
            <p>Otro de los puntos fundamentales de la justicia transicional son la reparaci&oacute;n a las v&iacute;ctimas
                y la no repetici&oacute;n. En este sentido, Antonia Urrejola, quien es Relatora Especial para Nicaragua
                y fue integrante del Grupo Internacional de Expertos Independientes (GIEI), que esclareci&oacute; la
                masacre de abril de 2018, dijo que la reparaci&oacute;n tiene un efecto no s&oacute;lo para las v&iacute;ctimas,
                sino tambi&eacute;n hacia la sociedad como una medida de no repetici&oacute;n, lo cual genera un efecto
                colectivo. &ldquo;Tiene un efecto hacia la sociedad toda porque cuando hablamos de reparaci&oacute;n es
                importante entender que no estamos hablando de una reparaci&oacute;n solo econ&oacute;mica, la reparaci&oacute;n
                tambi&eacute;n puede ser estructural&rdquo;, agreg&oacute;.</p>
            <p>El reto en Nicaragua es enorme. La Coalici&oacute;n por la Justicia se&ntilde;ala que &ldquo;la impunidad
                pactada ya no es una opci&oacute;n como lo fue en el pasado&rdquo;. Y aunque en el pa&iacute;s a&uacute;n
                no hay condiciones para un cambio democr&aacute;tico, porque no hay voluntad pol&iacute;tica de la
                pareja Ortega Murillo, los expertos tienen claro que el gobierno que tenga en sus manos la transici&oacute;n
                a la democracia tiene el deber de llevar ante los tribunales a quienes se hayan visto implicados en
                violaciones a los derechos humanos.</p>

