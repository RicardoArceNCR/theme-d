                existen en Nicaragua. El constitucionalista dijo que para que haya justicia transicional, al menos como
                concepto, debe existir un acuerdo pol&iacute;tico entre las partes, los sandinistas y antisandinistas.
                &ldquo;Si un nuevo gobierno impone la justicia a los sandinistas, no ser&iacute;a una justicia
