                    <h1 class="bukele-tc1 my-4 text-center">Una norma técnica “para salvar la vida de las mujeres”</h1>
                    <p>En diciembre del 2019, <a
                                href="https://www.nacion.com/el-pais/salud/presidente-alvarado-tras-firmar-la-norma-tecnica/NFUWHJTCDJAJRLISYOQ5QRB46A/story/">el
                            presidente Carlos Alvarado firm&oacute; la norma t&eacute;cnica</a> sobre el aborto terape&uacute;tico
                        para &ldquo;salvar la vida de las mujeres&rdquo;.</p>
                    <p>La disposici&oacute;n otorga seguridad jur&iacute;dica para la implementaci&oacute;n del aborto
                        con la exigencia de cumplir un procedimiento para la aprobaci&oacute;n de cada caso. Los equipos
                        de especialistas tardaron m&aacute;s de cuatro a&ntilde;os en dise&ntilde;arla.</p>
                    <p>La elaboraci&oacute;n de la norma t&eacute;cnica se dio por la <a
                                href="https://elpais.com/internacional/2018/07/17/mexico/1531781375_790446.html">presi&oacute;n
                            que recibi&oacute; Costa Rica con los casos de Ana y Aurora</a> presentados ante la Comisi&oacute;n
                        Interamericana de Derechos Humanos (CIDH). Ambas mujeres se vieron obligadas a dar a luz pese a
                        que sab&iacute;an que los beb&eacute;s no ten&iacute;an posibilidades de sobrevivir.</p>
                    <p>La historia de Aurora es una de las m&aacute;s conocidas en el pa&iacute;s. Su beb&eacute; se
                        desarroll&oacute; con la pared abdominal abierta y los &oacute;rganos vitales expuestos, por lo
                        que los m&eacute;dicos supieron desde las primeras semanas que no podr&iacute;a vivir. Y, pese a
                        que la situaci&oacute;n tambi&eacute;n representaba un riesgo grave para la salud mental de
                        ella, el Estado se neg&oacute; a interrumpir la gestaci&oacute;n.</p>
                    <p>La norma t&eacute;cnica se basa en lo que dice el art&iacute;culo 121 del C&oacute;digo Penal
                        que, desde 1970, establece la figura del aborto impune: &ldquo;No es punible el aborto
                        practicado con consentimiento de la mujer por un m&eacute;dico o por una obst&eacute;trica
                        autorizada, cuando no hubiere sido posible la intervenci&oacute;n del primero, si se ha hecho
                        con el fin de evitar un peligro para la vida o la salud de la madre y este no ha podido ser
                        evitado por otros medios&rdquo;.</p>
                    <p>En aquel entonces, Alvarado aclar&oacute; que la norma t&eacute;cnica no legaliza el aborto libre
                        en Costa Rica, sino que estandariza el abordaje m&eacute;dico de un procedimiento que permite
                        interrumpir el embarazo cuando la vida de la mujer corra peligro.</p>
                    <p>No obstante, tras la firma de la norma, la interrupci&oacute;n del embarazo para proteger la
                        salud y vida de la madre <a
                                href="https://www.nacion.com/el-pais/salud/ccss-presenta-a-salud-protocolo-para-atender/VMDD5YRDKBFLTB4U2NUWA3S34I/story/">debe
                            pasar por un proceso de revisi&oacute;n</a>, que incluye el criterio colegiado de m&eacute;dicos
                        especialistas en Ginecoobstetricia, y la firma de un consentimiento informado de la mujer.</p>
                    <p>&ldquo;La norma t&eacute;cnica es un gran paso en Costa Rica. Pero, para que se traduzca en
                        acceso verdadero a servicios de salud, debe pasar por un proceso amplio de socializaci&oacute;n,
                        contar con el acompa&ntilde;amiento de la estructura del gobierno y de otros organismos sociales&rdquo;,
                        dijo Guillermo Ortiz, ginec&oacute;logo obstetra salvadore&ntilde;o y experto cl&iacute;nico
