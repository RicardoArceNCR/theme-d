                        se necesita que las mujeres sepan que existe una normativa que las protege y que es una opci&oacute;n
                        para cuando ellas tengan un riesgo en su embarazo que ponga en peligro su salud o su vida&rdquo;.</p>
                    <h1 class="bukele-tc1 my-4 text-center">Relevancia de la norma técnica</h1>
                    <p>&ldquo;Costa Rica ha sido un ejemplo en salud para la regi&oacute;n centroamericana y es
                        fundamental que esta norma t&eacute;cnica realmente sea aplicada porque eso reducir&iacute;a
                        gran parte de las barreras que enfrentan las mujeres que requieren servicios m&eacute;dicos de
                        calidad&rdquo;, seg&uacute;n el especialista en ginecobstetricia de Ipas CAM, Guillermo Ort&iacute;z.</p>
                    <p>Antes de que entrara en vigencia la norma t&eacute;cnica en el pa&iacute;s, era com&uacute;n que
                        los servicios de salud aplicaran el art&iacute;culo 121 del C&oacute;digo Penal a medias, es
                        decir, practicaban el aborto terap&eacute;utico en pocos casos y, cuando lo hac&iacute;an, solo
                        se tomaban en cuenta aquellos en los que la vida de la madres estaba en riesgo, pero no as&iacute;
                        la salud. Esto fue lo que sucedi&oacute; en los casos de Ana y Aurora y por eso ellas decidieron
                        demandar al Estado.</p>
                    <p>&ldquo;Con la norma t&eacute;cnica se puso sobre la mesa que la mujer tambi&eacute;n pod&iacute;a
                        tener un futuro riesgo a su salud y no solo a su vida y que esos casos tienen que ser evaluados.
                        Antes hab&iacute;a cierta inseguridad jur&iacute;dica, los m&eacute;dicos no sab&iacute;an o cre&iacute;an
