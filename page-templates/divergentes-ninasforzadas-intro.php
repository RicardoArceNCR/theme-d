                    <p>Hablar de aborto o interrupci&oacute;n del embarazo en Centroam&eacute;rica es un tema tab&uacute;
                        debido a la animadversi&oacute;n creada por sectores religiosos y conservadores, cuyas posturas
                        est&aacute;n m&aacute;s cerca del mito que de la evidencia cient&iacute;fica. Estos discursos
                        que se autodenominan &ldquo;provida&rdquo; han logrado doblarle el brazo al estado laico, y
                        conseguido penalizar legalmente la interrupci&oacute;n del embarazo, sin importar el problema de
                        salud p&uacute;blica que han impuesto.</p>
                    <p>Los pol&iacute;ticos, que no escuchan las demandas de las mujeres, y que sobre sus cuerpos
                        negocian para sacar r&eacute;ditos pol&iacute;ticos de una sociedad conservadora, han aprobado
                        leyes que ponen a 3 de los pa&iacute;ses centroamericanos entre los 16 en el mundo, a la par de
                        Irak, Congo y Egipto, que no contempla la interrupci&oacute;n del embarazo ni cuando la vida de
                        la mujer est&aacute; en peligro.</p>
                    <p>Aunque hay avances como en el caso de Costa Rica con la reciente aprobaci&oacute;n de una &ldquo;norma
                        t&eacute;cnica&rdquo;, la interrupci&oacute;n del embarazo es todav&iacute;a una gran deuda de
                        Centroam&eacute;rica con sus mujeres. Por eso este especial period&iacute;stico encabezado por
                        DIVERGENTES busca en este D&iacute;a Internacional de la Mujer retratar cu&aacute;l es el estado
                        de la penalizaci&oacute;n del aborto en la regi&oacute;n. Entender c&oacute;mo las mujeres est&aacute;n
                        siendo afectadas, y cu&aacute;les son los retos que quedan para lograr una despenalizaci&oacute;n
                        del aborto como lo recomiendan organismos internacionales de derechos humanos y de salud, como
                        la Organizaci&oacute;n de las Naciones Unidas (ONU) y la Organizaci&oacute;n Mundial de la Salud
                        (OMS), y como sucedi&oacute; en Argentina a finales de 2020. Un tema urgente.</p>
