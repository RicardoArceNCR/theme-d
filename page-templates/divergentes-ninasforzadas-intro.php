                        permite de manera limitada el aborto cuando la continuaci&oacute;n del embarazo represente un
                        riesgo para la vida de la mujer. Mientras que la legislaci&oacute;n paname&ntilde;a permite
                        tambi&eacute;n el aborto cuando el embarazo es producto de violaci&oacute;n.</p>
                    <p>Sin embargo, en la pr&aacute;ctica las mujeres enfrentan barreras institucionales para acceder a
