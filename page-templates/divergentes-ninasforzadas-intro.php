                    <p><strong>&iquest;Cu&aacute;l ser&iacute;a el impacto en la vida de las mujeres centroamericanas si
                            se logra tener interrupciones del embarazo legales? </strong></p>
                    <p>Cuando en Centroam&eacute;rica logremos despenalizar el aborto, las mujeres podr&aacute;n acceder
                        a procedimietos seguros. Por supuesto que la despenalizaci&oacute;n del aborto tiene que venir
                        acompa&ntilde;ada de pol&iacute;ticas de prevenci&oacute;n, de planificaci&oacute;n familiar y
                        de educaci&oacute;n sexual integral. Eso es muy importante.</p>
                    <p>Ninguna mujer aborta por deporte. Ninguna organizaci&oacute;n est&aacute; promoviendo el aborto
                        en s&iacute; mismo. Lo que estamos promoviendo es que pueda ser seguro. Cuando se despenalice el
                        aborto en Centroam&eacute;rica, las mujeres tendr&aacute;n la posibilidad de acceder a servicios
                        de salud de calidad. Adem&aacute;s, evitar&aacute;n el sufrimiento y las consecuencias de estar
                        enfrentando un embarazo no planeado o no deseado, y evitar&aacute;n poner en riesgo su vida y su
                        salud en procedimientos clandestinos. Muchas mujeres, cuando buscan el apoyo de alg&uacute;n m&eacute;dico
                        en los lugares donde est&aacute; penalizado, se vuelven v&iacute;ctimas de estos m&eacute;dicos
                        que las extorsionan; en muchos casos abusan de ellas porque est&aacute;n totalmente
                        desprotegidas.</p>
                    <p>Lo que las mujeres en Centroam&eacute;rica van a poder vivir es lo que vivimos las mujeres en
                        Ciudad de M&eacute;xico o ahora las mujeres en Argentina. Hubo esa absurda idea de que en cuanto
                        se despenaliz&oacute; en Argentina, las mujeres iban a embarazarse en olas y olas para poder ir
                        a abortar. Y esto no pasa. La despenalizaci&oacute;n del aborto no incrementa el n&uacute;mero
                        de abortos, lo que s&iacute; incrementa son los abortos que son seguros. Lo que las mujeres en
                        Centroam&eacute;rica hoy no tienen y que podr&iacute;an tener es eso, abortos y servicios
                        seguros.</p>
                    <p>La otra cosa que las mujeres hoy en Centroam&eacute;rica no tienen, y que tendr&aacute;n una vez
                        que se despenalice el aborto, es que ser&aacute;n menos v&iacute;ctimas de injusticias. Lo que
                        ha pasado con la penalizaci&oacute;n total del aborto es que no solamente se castiga a aquellas
                        mujeres que se han practicado un aborto sino tambi&eacute;n a quienes sufrieron una emergencia
                        obst&eacute;trica.</p>
                    <p>Hay dos casos como estos en El Salvador, que en este momento se est&aacute;n discutiendo en la
                        Corte Interamericana de Derechos Humanos. Uno de ellos es el de Manuela. La audiencia es la pr&oacute;xima
                        semana. Manuela es una mujer que es encarcelada por el crimen de aborto, cuando lo que ella tuvo
                        fue una emergencia obst&eacute;trica. El Estado falla en su obligaci&oacute;n de proteger a la
                        mujer y de brindarle salud; lo que hace es meterla a la c&aacute;rcel. Por supuesto, es una
                        mujer pobre, una mujer ind&iacute;gena y sin recursos. Entonces, lo que vamos a ver en Centroam&eacute;rica
                        cuando logremos despenalizar es una reducci&oacute;n significativa en estos casos de injusticia,
                        no solamente en el tema de aborto, sino el tema de emergencia obst&eacute;trica, como en el caso
                        de Manuela y en el caso de Beatriz.</p>
                    <p><strong>&iquest;C&oacute;mo cambiar esta realidad para las mujeres cuando contra la interrupci&oacute;n
                            del embarazo abundan argumentos contrarios, basados en la religi&oacute;n, mitos, tab&uacute;,
                            y nada de evidencia cient&iacute;fica? </strong></p>
                    <p>Tristemente Centroam&eacute;rica sigue siendo una regi&oacute;n oscurantista, donde las mujeres
                        estamos en riesgo. Las mujeres sentimos temor desde la calle, pero tambi&eacute;n de los
                        sistemas que no funcionan. &iquest;C&oacute;mo cambiar esto? El otro lado de la moneda que tiene
                        Centroam&eacute;rica es un movimiento social, un movimiento feminista y de mujeres s&oacute;lido,
                        vibrante... Centroam&eacute;rica es una regi&oacute;n que ha sufrido muchos problemas sociales,
                        dictaduras, matanzas y desastres naturales. Es una regi&oacute;n que ha sufrido mucho, pero muy
                        resiliente.</p>
                    <p>Uno de los privilegios de trabajar en Centroam&eacute;rica es que las centroamericanas, los
                        centroamericanos est&aacute;n hechos de un material resiliente, fuerte. Lo que necesitamos es
                        que las fuerzas pol&iacute;ticas y sociales en Centroam&eacute;rica puedan alejarse de esta visi&oacute;n
                        religiosa. Los grupos religiosos sin duda juegan un papel importante, tanto la Iglesia Cat&oacute;lica
                        como el movimiento evangelista que ha cobrado mucha fuerza, entre otros muchos. Que podamos
                        pugnar por un Estado laico, un Estado que genere pol&iacute;ticas p&uacute;blicas y legislaci&oacute;n
                        desde una visi&oacute;n de atender a todos sus ciudadanos en un enfoque de derechos humanos, de
                        justicia social y de equidad de g&eacute;nero.</p>
                    <p>Si podemos pugnar por Estados laicos, podremos avanzar mejor y empezar a trabajar el tema de
                        mitos y estigmas alrededor alrededor del aborto. Al final de cuentas, el tema de aborto tiene
                        que ver mucho m&aacute;s con esta idea de deconstruir el rol de las mujeres, no desde una visi&oacute;n
                        tradicional que dicta que nosotras deber&iacute;amos ser siempre madres. Como si ese fuera tu
                        &uacute;nico objetivo en la vida. Y entonces las mujeres que decidimos algo diferente, o las que
                        deciden interrumpir un embarazo, son como contra natura. Pero cuando vemos hacia d&oacute;nde va
                        creciendo la sociedad, vemos que necesitamos romper estos mitos. Creo que en Centroam&eacute;rica
                        hay el material. Espero que la clase pol&iacute;tica empiece a ver esta cruel realidad para que
                        la situaci&oacute;n pueda cambiar.</p>
