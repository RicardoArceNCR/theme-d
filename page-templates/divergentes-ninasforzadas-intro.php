                        muerte. Una de las expresiones m&aacute;s claras de ello es la penalizaci&oacute;n del aborto
                        terape&uacute;tico en la mayor&iacute;a de los pa&iacute;ses del istmo, una situaci&oacute;n jur&iacute;dica
                        y social que solapa en el fondo la violencia de g&eacute;nero en varias de sus formas: abusos
