                    <p><strong>&iquest;Cu&aacute;l es el estado de Centroam&eacute;rica frente a la interrupci&oacute;n
                            legal del embarazo en comparaci&oacute;n a otras regiones del mundo?</strong></p>
                    <p></p>
                    <p>Desafortunadamente es la regi&oacute;n del mundo que tiene el mayor n&uacute;mero de pa&iacute;ses
                        que criminalizan totalmente el aborto. Tenemos siete pa&iacute;ses en la regi&oacute;n
                        centroamericana, de los cuales tres penalizan el aborto en todas sus formas. Es algo
                        verdaderamente muy radical en el reconocimiento de los derechos sexuales y reproductivos. Hay
                        una gama en el reconocimiento de este derecho. Pa&iacute;ses que tienen pol&iacute;ticas m&aacute;s
                        progresistas en estos temas y que reconocen el derecho de la mujer a decidir sobre su sexualidad
                        y su reproducci&oacute;n con el objetivo de eliminar la maternidad forzada, y asegurar que todos
                        los embarazos sean deseados. Otros pa&iacute;ses que permiten y garantizan a las mujeres el
                        acceso al aborto por decisi&oacute;n o por las condiciones que enfrentan. Y del otro lado de esa
                        gama se encuentran pa&iacute;ses como Nicaragua, El Salvador y Honduras, donde se penaliza
                        totalmente el aborto.</p>
                    <p>Esta penalizaci&oacute;n total tambi&eacute;n crea un problema para los m&eacute;dicos que tienen
                        que asegurar la salud de las mujeres. Es un dilema. Por ejemplo, en Nicaragua, donde hubo un
                        caso de una mujer que enfrentaba un embarazo ect&oacute;pico, es decir que se coloca fuera del
                        &uacute;tero. Naturalmente, en el resto del mundo, a estos embarazos se les practica una
                        interrupci&oacute;n del embarazo, porque no prosperan; al momento que va creciendo el producto,
                        revienta la trompa de falopio. En cambio en pa&iacute;ses como Nicaragua, los m&eacute;dicos
                        tienen que esperar a que ocurra una emergencia obst&eacute;trica, es decir, esperar a que la
                        mujer le reviente la trompa de falopio para poder intervenir. Y a&uacute;n cuando tienen que
                        intervenir, esperan a que no haya latido fetal. Esto pone en grav&iacute;simo riesgo a las
                        mujeres. Los m&eacute;dicos quedan en una situaci&oacute;n muy compleja. Entonces, la interrupci&oacute;n
                        legal del embarazo en Centroam&eacute;rica es un pendiente enorme. Es la realidad m&aacute;s
                        retr&oacute;grada y m&aacute;s violenta hacia las mujeres que existe en el mundo.&nbsp;</p>
                    <p><strong>&iquest;Cu&aacute;les son los principales obst&aacute;culos que impiden la interrupci&oacute;n
                            legal de los embarazos?</strong></p>
                    <p></p>
                    <p>Una parte, sin duda, es la poca voluntad pol&iacute;tica que existe para para cambiar las
                        legislaciones. Mientras las legislaciones no cambien, muy dif&iacute;cilmente las mujeres van a
                        poder tener acceso a la interrupci&oacute;n del embarazo sin restricciones. A veces la legislaci&oacute;n
                        no es suficiente. Hemos visto que han habido pa&iacute;ses que han ampliado causales. Por
                        ejemplo, en el caso de Costa Rica, donde el aborto es permitido cuando el embarazo pone en
                        riesgo la salud o la vida de las mujeres. Pero la ley se aprob&oacute; y pasaron diez a&ntilde;os
                        para que se creara el protocolo que operara la ley. La ley exist&iacute;a pero era letra muerta
                        y apenas ahora, hasta este gobierno de Carlos Alvarado, el a&ntilde;o pasado se aprob&oacute; la
                        norma t&eacute;cnica. Entonces es la legislaci&oacute;n, pero tambi&eacute;n que existan los
                        protocolos, la capacitaci&oacute;n a los m&eacute;dicos para que puedan practicar y dar
                        seguimiento a estos servicios. Que haya misoprostol y mifepristona y todos los insumos m&eacute;dicos
                        necesarios. Pero sobre todo, necesitamos combatir el estigma y la discriminaci&oacute;n. Este
                        estigma ha sido creado por los grupos anti derechos con la intenci&oacute;n de penalizar
                        legalmente, y tambi&eacute;n socialmente, a las mujeres que se atreven a querer ser due&ntilde;as
                        de su sexualidad y de sus decisiones reproductivas. Sin duda en la regi&oacute;n tenemos
                        barreras en todos estos aspectos. </p>
                    <p><strong>De cierta manera lo dijo, Centroam&eacute;rica es una regi&oacute;n bastante marcada por
                            la pobreza, pero tambi&eacute;n por la violencia de g&eacute;nero como norma social.
                            &iquest;C&oacute;mo afecta la calidad de vida f&iacute;sica y emocional de las mujeres el
                            hecho de no contar con una interrupci&oacute;n del embarazo seguro a su
                            pa&iacute;s?</strong></p>
                    <p></p>
                    <p>Tocas dos elementos que son centrales para entender lo cruel que son las pol&iacute;ticas que
                        penalizan el aborto. Uno es la violencia de los grupos m&aacute;s conservadores, en esa visi&oacute;n
                        simplista del aborto, dicen &ldquo;Pues que no se embaracen. Si no quieren tener hijos, &iquest;para
                        qu&eacute; se embarazaron?&rdquo;. Lo dicen haciendo caso omiso a una realidad tristemente
                        permanente en nuestra regi&oacute;n, donde hay miles de mujeres que cada d&iacute;a sufren
                        violencia sexual. En Ipas hicimos un an&aacute;lisis a profundidad sobre el tema de violencia
                        sexual e infancia, y tristemente mucha de esta de estas violaciones suceden en el seno de la
                        familia. La gran mayor&iacute;a de estas violaciones son perpetradas por alguien conocido de la
                        v&iacute;ctima; es decir, el padrastro, el abuelo, el t&iacute;o, el primo, el hermano o el
                        sacerdote, el maestro. Entonces estas no son mujeres que decidieron embarazarse, estas son
                        mujeres que son v&iacute;ctimas... Y el Estado y la sociedad deber&iacute;amos proteger a las v&iacute;ctimas
                        de las sobrevivientes de violencia sexual. Pero en lugar de protegerlas, lo que hacemos es
                        revictimizarlas con la carga de un embarazo y despu&eacute;s la responsabilidad de un hijo o una
                        hija, cuando ellas no decidieron. Esta visi&oacute;n simplista de los grupos conservadores es
                        absurda.</p>
                    <p>El segundo punto es la pobreza. Hablo de pobreza econ&oacute;mica, pero tambi&eacute;n de pobreza
                        educativa. Estos mismos grupos conservadores, que critican a las mujeres y que impulsan la
                        maternidad forzada, son los mismos que est&aacute;n en contra del acceso a anticonceptivos y que
                        los servicios p&uacute;blicos brinden anticonceptivos de manera gratuita. Est&aacute;n en contra
                        de la educaci&oacute;n sexual. Nosotras sabemos, y esto est&aacute; probado, que penalizar el
                        aborto no reduce la incidencia del aborto. La mujer que enfrenta un embarazo no planeado, no
                        deseado, que es v&iacute;ctima de una de violaci&oacute;n, y necesita interrumpir el embarazo,
                        lo va a hacer de manera segura o insegura, legal o ilegal.&nbsp;</p>
                    <p>Aqu&iacute; el debate no es aborto s&iacute; o aborto no. Aqu&iacute; el debate es sobre aborto
                        seguro o aborto inseguro. La mujer decidida lo va a hacer con hierbas, con un gancho o de las
                        maneras m&aacute;s inseguras pero disponibles, porque la penalizaci&oacute;n del aborto no
                        reduce la necesidad del mismo.</p>
                    <p>Lo que s&iacute; reduce la necesidad del aborto es el acceso amplio a m&eacute;todos
                        anticonceptivos y una educaci&oacute;n integral en sexualidad que, adem&aacute;s de dar
                        informaci&oacute;n a las y los j&oacute;venes, reduzca la violencia de g&eacute;nero; que eduque
                        a nuestros ni&ntilde;os y a nuestros j&oacute;venes para dejar de normalizar la violencia de g&eacute;nero.
                        Eso s&iacute; reduce la incidencia de aborto. Pero tristemente, los mismos grupos, las mismas
                        voces que est&aacute;n en contra de despenalizar el aborto, son exactamente las mismas que tambi&eacute;n
                        est&aacute;n en contra de lo &uacute;nico que lo puede reducir, que es el acceso a
                        anticonceptivos y la educaci&oacute;n sexual.</p>
                    <p>En Centroam&eacute;rica, con los &iacute;ndices de violencia que tenemos, que enfrentamos las
                        mujeres todos los d&iacute;as y con los niveles de pobreza que vive la regi&oacute;n, y que est&aacute;n
                        siendo exacerbados por la pandemia de COVID-19, lo que vemos es m&aacute;s necesidad de
                        programas de educaci&oacute;n sexual integral, programas de salud sexual y reproductiva y de
                        despenalizaci&oacute;n del aborto.&nbsp;</p>
