                hasta terminar en esta condena.&nbsp;</p>
            <p>El veredicto de culpabilidad para Garc&iacute;a muestra la evoluci&oacute;n de la represi&oacute;n pol&iacute;tica
                a trav&eacute;s de la instrumentalizaci&oacute;n del aparato judicial: la reciente decisi&oacute;n del r&eacute;gimen
                sandinista de que la Fiscal&iacute;a fabrique delitos comunes (sobre todo narcotr&aacute;fico), cuando
                ya no tienen razones convicentes para imputar m&aacute;s casos de terrorismo que permitan seguir
                criminalizando y desarticulando la disidencia, explica Gonzalo Carri&oacute;n, abogado y defensor de
