            <h1 class="mercenarios-armados">Procesados por <span> “terrorismo”</span></h1>
            <p>De los 1,250 presos pol&iacute;ticos registrados, 802 personas fueron procesadas por las instancias
                judiciales del r&eacute;gimen, es decir que no todos los juicios concluyeron en condena. Y no por
                condescend&iacute;a del r&eacute;gimen, sino porque en 2018 hubo negociaciones entre el Gobierno y la
                oposici&oacute;n, lo que combinado con la presi&oacute;n internacional, deriv&oacute; en las
                excarcelaciones de la mayor&iacute;a de los reos de conciencia. A eso debe sumarse la controversial ley
                de amnist&iacute;a que el Gobierno aprob&oacute; en junio de 2019 y suspendi&oacute; varios juicios.
                Pero como el r&eacute;gimen no ces&oacute; las capturas por razones pol&iacute;ticas, la base de datos
                document&oacute; las detenciones que continuaron hasta finales de 2020.</p>
            <p>De las 802 personas procesadas, 354 fueron condenadas. Mientras a 448 les abrieron causas judiciales que
                no concluyeron en condenas. El an&aacute;lisis de datos logr&oacute; obtener informaci&oacute;n
                exhaustiva de los cargos judiciales impuestos a 515 de los 802 procesados, lo que permite identificar
                una gama de delitos grav&iacute;simos que no han sido impuestos a quienes las v&iacute;ctimas de la
                masacre se&ntilde;alan como perpetradores de ejecuciones extrajudiciales, asesinatos, torturas, abuso
