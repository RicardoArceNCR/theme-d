            <p>La experiencia de este matrimonio con la justicia nicarag&uuml;ense expone el doble rasero con el que el
                Gobierno Ortega-Murillo ha tratado a los ciudadanos que considera &ldquo;golpistas&rdquo;: La imposici&oacute;n
                de delitos igual de exacerbados que las penas de c&aacute;rceles contra centenares de presos pol&iacute;ticos
                desde 2018. Una justicia severa que dista diametralmente de la impunidad que cobija a polic&iacute;as,
                paramilitares y operadores intelectuales que perpetraron la &ldquo;masacre&rdquo; y los &ldquo;cr&iacute;menes
