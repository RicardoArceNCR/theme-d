            <h1 class="mb-4 text-left">Militares, herramienta de gobernanza e impunidad </h1>
                <p>Los militares han sido una herramientas de gobernanza por excelencia en El Salvador. Ese poder se ha visto reflejado en la impunidad con la que han enfrentado la justicia después de la guerra civil (1980-1992). Cada gobierno que ha llegado al poder, sea de izquierda, derecha o de amalgama política —como el de Bukele —ha preferido encubrir los crímenes de guerra a tener a la FAES como enemigo. </p>
                <p>El Salvador fue fundado como un país que siempre luchó contra un enemigo en común, y sus clases dominantes siempre usaron a los militares para dar esa pelea. Uno de los ejemplos dentro de la historia reciente fue la lucha contra el comunismo. No los lograron derrotar totalmente. Con ellos se tuvieron que sentar a negociar después de 12 años de cruenta guerra civil.</p>
                <p>A diferencia de la década de los ochenta, que fue una época de protagonismo y poder para la FAES, en los noventas luego de los acuerdos de paz, cuando no existía el enemigo en común, los militares perdieron relevancia. Pero esto no duró mucho. En el 2003 regresaron al espacio público con el expresidente Francisco Flores, acusado de corrupción. Flores convocó a los militares a uno de los bastiones del barrio 18-Revolucionarios, la colonia Dina, para quitar del camino al nuevo "enemigo del pueblo": las pandillas. </p>
                <h1 class="mb-4 text-left">El Ejército contra los pandilleros </h1>
                <p>Estos planes que utilizan a militares en tareas de servicio público se mantuvieron en los gobiernos siguientes: Los dos gobiernos de derecha (Francisco Flores y Antonio Saca) y los dos de izquierda (Mauricio Funes y Salvador Sánchez Cerén)... y han sido continuados por la administración actual con su denominado y controvertido “plan control territorial”. </p>
                <p>Aunque la guerra antipandillas se mantiene con Bukele, el enemigo en común ha sufrido una variación. Las pandillas pasaron a ser parte y actores de un problema más grande: los partidos políticos. Así es como los militares pasaron de cuidar perímetros en penales a meterse a la Asamblea. La fórmula es sencilla: el enemigo se mata a la balazos y las balas las tienen los militares.</p>
                <p>Las cuotas de poder de las elites en El Salvador se han ido construyendo desde hace un siglo. Tanto la oligarquía como los militares han aprendido a convivir para no chocar entre ellos, siempre entendiendo que su poder llega hasta donde comienza el de Estados Unidos. Una investigación hecha por el periódico El Faro confirmó que todos los sucesos del 9 de febrero se dieron bajo el visto bueno del embajador de Estados Unidos, Ronald Johnson, pese a las negativas y la preocupaciones de otros embajadores, como los representantes de la Unión Europea. </p>
                <p>El futuro de El Salvador con o sin pandemia, con o sin Bukele, es imprevisible, pero si algo es seguro, es que los militares van a estar en él. </p>

