                <p><b>SAN SALVADOR, EL SALVADOR</b>–. El 9 de febrero de 2020, cuando el presidente Nayib Bukele usurpó el órgano legislativo salvadoreño con la excusa de exigir la aprobación de un préstamo para equipo de seguridad para policías y militares, se amalgamaron dos procesos en este pequeño país centroamericano: la militarización y la religión. </p>
                <p>El primer proceso, con sus pausas y sus obstáculos, inició a principios del siglo XX, cuando las oligarquías cafetaleras le dieron a la Fuerza Armada (FAES) privilegios que le permitieron dejar de ser simples soldados para transformarse en una élite política. Todo esto se cristalizó cien años después con Bukele, haciendo algo que nunca se había visto en la historia del país: sentándose en la silla del presidente de la Asamblea Legislativa rodeado y protegido por militares. </p>
                <p>Bukele se subió a la tarima junto al jefe del Estado Mayor Presidencial, el Coronel Manuel Antonio Acevedo. En su discurso, el mandatario le pidió a las aproximadas 5 mil personas —que su partido, Nuevas Ideas, llevó a la plaza— a que pensaran en sus familiares muertos. Culpó a los diputados por negociar con la “sangre del pueblo” y no aprobar, cuando él quiso, el préstamo de 109 millones de dólares destinados a equipo de seguridad. Lo que en un inicio fue fiesta, mutó a un grupo de gente extasiada, exigiendo lo que el presidente les pidió que exigieran: la insurrección. </p>
                <h1 class="mb-4">Una trayectoria de insurrecciones </h1>
                <p>En El Salvador existe una trayectoria de insurrecciones. Una de las más importantes sucedió en 1944, cuando un movimiento urbano sacó del poder al General Maximiliano Martínez, el primer dictador militar de este país centroamericano. Lo de Bukele este 9 de febrero, no era ni por cerca una insurrección, sino algo un poco más complejo.</p>
                <p>Con la marcha granadera de fondo entre cadetes, grupos élites de la FAES y seguridad privada, Bukele fue directo a la silla del presidente de la Asamblea Legislativa. Dio la bienvenida a un hemiciclo inundado de soldados y a unos cuantos diputados presentes, la mayoría de GANA, el partido que lo llevó al poder. Los diputados de Arena, un partido de derecha y oposición mayoritaria en el legislativo, se ausentó, pese a su pasado militar: Arena fue dirigido por el Mayor Roberto d'Aubuisson que, entre varias cosas, quedará plasmado en la historia como el responsable del asesinato de Monseñor San Óscar Arnulfo Romero en 1980, en su papel como líder de “los escuadrones de la muerte”, un grupo de paramilitares que ejecutó, violó y asesinó a miembros de la guerrilla de izquierda. </p>
                <p>Bukele terminó de felicitar a quienes habían cumplido sus órdenes, y como si fuera su autoridad, convocó a la discusión de temas de seguridad. Después se llevó las manos a la cara y fue así, como un caudillo, que se sentó a rezar rodeado por militares en la silla de la autoridad máxima de otro órgano, mientras la gente afuera pedía insurrección. </p>
