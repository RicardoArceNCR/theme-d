                <h1 class="mb-4 text-left">Falencias y expectativas</h1>
                <p>La vulnerabilidad frente a la corrupción es otro elemento que persiste en la actual Fuerza Pública. Prueba de eso son las cárceles, que en vez de ser centros de resocialización, se han convertido en espacios de negocios que son disputados fieramente -el año pasado 13 reclusos perdieron la vida en una reyerta-, y en los que participan hasta los custodios. En las requisas se han encontrado armas, celulares, cigarrillos drogas y todo tipo de artículos. Para contrarrestar esta situación, Quezada propone la creación de una policía carcelaria que esté bajo las órdenes de un civil.</p>
                <h1 class="mb-4 text-left">Saturación de rangos superiores </h1>
                <p>El autoritarismo se ha manifestado durante la implementación de una estricta cuarentena, con casos de abusos de fuerza y de negligencia. El más lamentable ocurrió cuando un hombre que atentaba contra su vida recibió dos disparos con un arma Taser a finales de mayo. Falleció después de haber sido presentado ante un juez de paz sin haber recibido atención médica previa. Asimismo, Camargo denuncia actos de discriminación contra extranjeros y la comunidad LGTB. </p>
                <p>En la policía actual todavía se acostumbra a que un director se congracie con sus subordinados mediante el otorgamiento de dádivas y ascensos, tal como ocurría en las FFDD, desconociendo méritos, rango y antigüedad. En la planilla del Ministerio de Seguridad aparecen cerca de 118 comisionados, con un salario promedio de cinco mil dólares cada uno -más de medio millón de dólares en total-, una cantidad que, según el exdirector de la Policía Nacional refleja una saturación en los rangos superiores. Según informes periodísticos, algunos comisionados, al igual que otros miembros de la policía, han estado involucrados en el tráfico de armas provenientes de Estados Unidos.</p>
                <p>El legado del militarismo también se visibiliza en los uniformes, con algunas unidades, entre ellas el SENAFRONT, utilizando camuflaje cuando operan en entornos urbanos.  “Esto les causa a los policías un daño terrible en su estructura mental y, por consiguiente, en su comportamiento; no saben realmente quiénes son, ni cómo comportarse, si como policías o soldados”.</p>
                <p>Para conocer si existe o no confusión entre las diferentes unidades que integran la Fuerza Pública, y sí se ha planteado la implementación de un sistema de méritos al momento de otorgar los ascensos, la semana pasada se envió un cuestionario por correo electrónico al Ministerio de Seguridad. Las preguntas no fueron contestadas.</p>
                   <p>El autoritarismo de antaño ha devenido hoy en una insensibilidad hacia los derechos humanos, advierte Camargo. Esto se traduce en actos de discriminación contra extranjeros y la comunidad LGBT. Esto atenta contra la cultura de paz que promueve la Estrategia Nacional de Seguridad Ciudadana 2017-2030, encaminada a cumplir con los Objetivos de Desarrollo Sostenible de la Organización de las Naciones Unidas.</p>
                <p>Los expertos concuerdan en que es tiempo de repensar a las instituciones de seguridad, para que sean “eficaces, responsables y transparentes”, para que vuelvan a incorporar a las comunidades, promoviendo la participación por encima del acto meramente represivo.</p>
