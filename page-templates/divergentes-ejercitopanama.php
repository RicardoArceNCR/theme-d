                <p><b>CIUDAD DE PANAMÁ, PANAMÁ</b>–. Hace 30 años que Panamá no tiene ejército. Fue disuelto tras la invasión de Estados Unidos. Desde entonces, la economía ha crecido de forma casi sostenida. Han gobernado siete presidentes, todos elegidos mediante el sufragio.</p>
                <p>Se creó, además, la Fuerza Pública, encargada de la seguridad y la defensa nacional tras el legado de represión de las Fuerzas de Defensa (FFDD), el brazo armado de la dictadura que controló el país entre 1968 y 1989. Pero algunas de las estructuras y vicios heredados de los militares persisten hasta el día de hoy.</p>
                <p>Históricamente, el militarismo panameño ha estado vinculado a las pugnas políticas, desde lo local, y a los cambiantes requerimientos de seguridad de los Estados Unidos. Empoderado como parte de una política de contención al comunismo, el 11 de octubre de 1968 se tomó el poder; primero como Guardia Nacional y, a partir de 1983, como las Fuerzas de Defensa (FFDD). La entidad estaba llamada a defender el Canal una vez pasara manos panameñas, en cumplimiento del Tratado de 1977, pero la invasión militar estadounidense puso fin al régimen militar.</p>
                <p>La vigilancia del Canal quedó, como siempre estuvo, en manos de los Estados Unidos. Es por ello que Francisco Quezada, ex mayor de las Fuerzas de Defensa que participó en la reestructuración de la policía durante el primer gobierno post invasión, afirma que esta tarea ya no justifica que Panamá tenga un ejército que “se descalificó con Noriega”. Sin embargo, aún existen unidades militarizadas dentro de la Fuerza Pública, como el Servicio Nacional de Fronteras (SENAFRONT) y el Servicio Nacional Aeronaval.</p>

                <h1 class="mb-4 text-left">Un ejército dentro de la policía</h1>
                <p>El SENAFRONT fue creado en el 2008 con la misión de resguardar las “fronteras terrestres de Panamá y proteger su soberanía e integridad territorial”. En realidad, funciona como un pequeño ejército dentro de la estructura de la Fuerza Pública. Formado por 11 batallones y con un presupuesto de 3, 635, 600 millones de dólares, tiene la mayoría de sus bases en Darién, donde a través de los años ha lidiado con grupos guerrilleros y criminales procedentes de Colombia.</p>
                <p>Pero su campo de acción no se limita a las zonas fronterizas. Es recordada su participación en la represión de las protestas del 2010 y 2012 en Chiriquí y Colón, que dejaron un saldo de ocho muertes y cientos de heridos. La abogada Gilma Camargo recuerda que se presentaron demandas nacionales e internacionales. “Panamá está usando el SENAFRONT como se ha utilizado la Guardia Nacional en los Estados Unidos: para ahuyentar manifestantes”, agrega por su parte el cineasta Xavier Ucar, quien actualmente trabaja en un documental sobre la época militar.</p>
                <p>Hoy en día, el SENAFRONT está metido en varios frentes: en la “securitización” de la respuesta a la pandemia, en el manejo de la situación de miles de migrantes que se encuentran varados tras el cierre de fronteras y en los operativos antidrogas -en los que también participa el SENAN.  “Nadie puede negar la importancia del establecimiento de fuerzas especiales y fronterizas para combatir el tráfico de personas y drogas, pero las de Panamá, además de ser represivas, responden una agenda de Estados Unidos”, indica Camargo.</p>
                <p>Para la jurista de derechos humanos, el problema radica en que “nunca hemos resuelto el tema de la dictadura y del abuso de autoridad”. Son estructuras pendientes de ser demolidas, como la Constitución de 1972, legado de los militares, que tiende a concentrar el poder en el Ejecutivo.</p>
