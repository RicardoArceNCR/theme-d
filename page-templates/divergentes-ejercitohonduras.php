                <p><b>TEGUCIGALPA, HONDURAS</b>–. En el 2007, en el gobierno del presidente Manuel Zelaya Rosales, los militares abandonaron las barracas para incursionar de nuevo a la palestra pública del poder político en Honduras, luego que el entonces mandatario les designara la administración de la estatal Empresa Nacional de Energía Eléctrica (ENEE) como parte de una junta interventora para rescatarla del descalabro económico del que aún no se recupera. El rescate de la estatal eléctrica ha sido el talón de Aquiles de las últimas administraciones gubernamentales.</p>
                <p>De la mano de Zelaya, los militares empezaron a tener un inusual rol protagónico al otorgarles funciones propias del ámbito de lo civil, hasta que el 28 de junio de 2009, los uniformados traicionarían la confianza del gobernante con un golpe de Estado. De esa época a la actual, su poder detrás del trono llegó para quedarse.</p>
                <p>Hoy son actores claves de las decisiones políticas. Ningún gobernante da un paso sin consultarles o tomarlos en cuenta, mientras ellos no dudan en recordar que son el “equilibrio” del poder y los “garantes” en su alternabilidad, pues tienen la función constitucional de la custodia de las urnas en época electoral, cada cuatro años.</p>
                <p>Atrás quedó el proceso de desmilitarización de la sociedad iniciada en los años noventa del siglo pasado. El golpe de Estado tumbó ese proceso y ahora ellos, sin estar al mando directo de la Nación, gobiernan tras el trono como lo fue desde la década de los ochenta.</p>

                <h1 class="mb-4 text-left">Tras el golpe, aliados incondicionales </h1>
                <p>Tras el golpe de Estado, los gobiernos del Partido Nacional, al frente del ex presidente Porfirio Lobo Sosa (2010-2014) y Juan Orlando Hernández (2014- a la fecha), han hecho de los militares sus aliados incondicionales para gobernar, en especial con las políticas de mano dura en materia de seguridad y defensa.</p>
                <p>Militares activos y en retiro están al frente de puestos claves como la Secretaría de Seguridad, la Secretaría de Defensa, las llamadas Zonas Exclusivas de Desarrollo Económico (ZEDES, un cuestionado y fracasado proyecto que busca crear soberanía paralela dentro del territorio con su propias reglas de gobernanza), una Subsecretaría de Estado en la Secretaría de Relaciones Exteriores y de Cooperación Internacional. También, son interventores en universidades públicas, manejan la administración de proyectos hidroeléctricos, de las cárceles del país, entre otros puestos públicos de la administración civil. Hoy copan más de una veintena de cargos como ministros, directores, asesores y hasta consejeros técnicos en materia laboral en la Secretaría del Trabajo. La última determinación fue entregarles millonarios recursos para el manejo de la producción agrícola en el país.</p>

                <p>Esa preponderancia ha sido más evidente en la administración del presidente Juan Orlando Hernández, quien asumió un segundo mandato en una cuestionada reelección presidencial, precedida de fuertes escándalos de corrupción y narcotráfico, al grado que uno de sus hermanos, el ex diputado Antonio “Tony Hernández”, ha sido condenado por narcotráfico en Estados Unidos y se le asocia con el poderoso cartel mexicano de Sinaloa que lideraba Joaquín “el Chapo” Guzmán. </p>
