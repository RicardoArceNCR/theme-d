                <h1 class="mb-4 text-left">“Garantes de la seguridad y el poder”  </h1>
                <p>El desgaste de las elites políticas, en especial los partidos políticos (84% de desconfianza según sondeo del Equipo de Reflexión, Investigación y Comunicación de los jesuitas de 2019) ha permitido a los militares ser garantes de una sensación de “seguridad y poder” para gobiernos débiles y con fuerte impugnación social como el del actual presidente Hernández.</p>
                <p>Ese poder se traduce en los aumentos presupuestarios, donde las Secretarías de Seguridad y Defensa, ostentan asignaciones presupuestarias más grandes que la de los operadores de justicia como es el Poder Judicial y el Ministerio Público, por citar un ejemplo.</p>
                <p>Para el 2020, el presupuesto de la Secretaría de Seguridad es de $265,132.750.56 millones, el de la Secretaría de Defensa $341,436.099.23 millones, mientras el del Poder Judicial es de $120,523.643.69 millones y el del Ministerio Público de $90,214.236.84 millones.</p>
                <p>Esos abultados presupuestos les han permitido aplicar, en total opacidad, su política de mano dura y remilitarización de la sociedad, pues se activaron leyes de protección como la del Consejo Nacional de Defensa y Seguridad y la Ley para la Clasificación de Documentos Públicos, conocida popularmente como la Ley de Secretos, que impide, entre otras acciones, conocer al detalle el destino de los fondos públicos administrados por los hombres de uniforme. A ello se suma la Ley de Seguridad Poblacional o “tasón de seguridad” mediante el cual el hondureño paga un impuesto destinado a la seguridad y obras de prevención, pero su destino ha sido declarado secreto por la sala constitucional del poder judicial.</p>
                <h1 class="mb-4 text-left">Crecen señalamientos de violaciones a derechos humanos</h1>
                <p>Esas prerrogativas y ascenso en las actividades de la administración pública, comienzan a pasar factura a los militares, al crecer las denuncias de abuso y violaciones de derechos humanos. En las elecciones de 2017, con el cuestionado triunfo reeleccionista de Hernández, informes de derechos humanos y del Alto Comisionado de los Derechos Humanos en Honduras, los sindican en la muerte de al menos 21 hondureños durante las protestas durante y posterior a los comicios. </p>
                <p>El Ministerio Público ha entablado las primeras acusaciones por esos y otros hechos, ha logrado, hasta ahora, la condena de 16 militares y 11 policías por delitos y violaciones humanitarias, pero ha denunciado la hostilidad de los uniformados por ser llevados a los tribunales. En el caso de los militares, las principales acusaciones recaen en la Policía Militar de Orden Público (PMOP), una nueva rama creada por el presidente Hernández, que hace las funciones de una especie de “guardia pretoriana” a su servicio incondicional.</p>
                <p>Estas acciones han llevado a que sus niveles de confianza caigan, según revela un sondeo del Instituto Universitario en Democracia, Paz y Seguridad de la estatal universidad nacional. La desconfianza es del 67.8% según la encuesta efectuada a fines de 2019. Pero hoy, por hoy, ellos son la carta de “garantía” de poder para una cuestionada elite política que pende también de otro aliado estratégico: la influencia de Washington que se refleja también en el poder militar.</p>
