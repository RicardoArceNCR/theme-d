                <p><b>Tegucigalpa, Honduras-.</b> En los últimos dos meses, tras el confinamiento por la pandemia en Honduras,
                    <a href="https://contracorriente.red/2020/05/22/sobrevivir-al-agresor-y-a-la-pandemia-en-honduras/" title="Sobrevivir al agregor y a la pandemia" target="_blank" class="covid-tc1">se aumentó en un 20% las denuncias por llamadas al 911</a> por violencia doméstica e intrafamiliar. Al
                    mismo tiempo, se activaron redes telefónicas de mujeres para apoyar y hacer frente a esto. Pero
                    también hay otro tipo de violencia, más silenciosa, como la que viven las madres solteras que en
                    Honduras representan el 33.5% de las jefaturas de hogar (unas 722,054 mujeres), según la última
                    encuesta de hogares en 2018 del Instituto Nacional de Estadística (INE). Ellas enfrentan la pandemia en
                    la calamidad que ha traído el desempleo y la restricción de salir a la calle a ganarse el sustento para sus
                    familias, mientras cuidan de sus hijos y se encargan de las actividades domésticas.</p>
                <p>Jessica Isla, de la Coalición Todas que aglutina diversas organizaciones feministas y de mujeres en
                    Honduras, asegura que así como le llegan llamadas de mujeres sobrevivientes de violencia que no han
                    sido correctamente atendidas en su emergencia, también recibe reportes de hospitales que <a href="https://contracorriente.red/2020/05/08/mujeres-con-menos-acceso-a-la-salud-durante-pandemia/" title="Niegan el derecho a la salud de las mujeres" target="_blank" class="covid-tc1">niegan el
                    derecho a la salud de las mujeres</a> y de comunidades donde se ha politizado una ayuda alimenticia del
                    gobierno que es insuficiente para las familias en precariedad</p>
                <p>“Muchos frentes se han politizado también porque se les da la bolsa solidaria y los víveres, pero no ha
                    habido una mirada estratégica a las necesidades de las mujeres, mucho menos de las mujeres que
                    sufren violencia, madres solteras, jóvenes con necesidades de su salud sexual reproductiva”, explica.</p>
                <p>Según un reporte de la Secretaría de Trabajo, el impacto económico de la pandemia en Honduras ha
                    dejado alrededor de 120 mil personas suspendidas de sus trabajos. En todo el país, 276 empresas se han
                    acogido al decreto de emergencia que contiene la Ley de Auxilio al Sector Productivo ante los efectos
                    de la pandemia de COVID-19 que permite la suspensión por 4 meses del personal sin goce de salario.
                    Muchos han sido despedidos. El apoyo prometido por el presidente Juan Orlando Hernández ante la
                    crisis económica consiste en una bolsa de alimentos valorada en 20 dólares y distribuida a través del
                    Programa “Honduras Solidaria”, cuestionado por corrupción en el manejo de la emergencia.</p>
                <p>Isla agrega que hay muchas mujeres desempleadas en el rubro de servicios y en el de la educación. “Por
                    ejemplo maestras en la universidad, que han sido contratadas por hora y las han despedido y muchas
                    son madres solteras, no hay claridad de una salida para ellas. Tenemos muchas redes de mujeres que
                    estamos viendo cómo sobreviven, hay una red de intercambio de productos pero incluso eso es difícil
                    por el tema de la movilización y lo otro es que las mujeres que están en el mercado, en las calles
                    sobreviviendo, están más expuestas al contagio”, explica.</p>
                <p>Jessica Isla también es madre y asegura que uno de los retos más grandes además de la carga de
                    trabajo es el impacto emocional que este encierro implica.
                </p>
                <p>“El tema de la sororidad en estos tiempos difíciles es importante, las redes de cuidado. Es difícil para
                    nosotras cuando alguien nos llama y no podemos atenderla y que la patrulla no va, terminamos llorando
                    nosotras también, no hay atención integral para las que cuidamos. Aquí también hablamos de las
                    doctoras, las enfermeras que son agredidas porque dicen que ellas son un peligro de contagio”, dice
                    Isla.
                </p>
                <p>Son tiempos de relaciones de ternura a la distancia -añade- y de pensar las formas en que se pueden
                    sostener estos esfuerzos económicos y de redes de mujeres. Ahora han funcionado las redes sociales,
                    el whatsapp, pero poco a poco los recursos disminuyen, las redes de distribución de bienes para el
                    consumo son cooptadas, el Estado se vuelve más represivo, el camino es más difícil. Tres mujeres
                    hondureñas nos cuentan cómo ha sido sobrellevar esta presión múltiple, porque han decidido no
                    quedarse de brazos cruzados.
                </p>
