                <p>Marta Izaguirre tiene 41 años y dos hijos, uno de 23 años y su hija de 25 que, como ella, también es
                    madre soltera. Marta es el sostén de toda la familia después de que su esposo terminara en la cárcel tras
                    agredirla. A su hija le pasó lo mismo, solo que su agresor no terminó en la cárcel, al menos sí lejos de sus
                    vidas. Marta dice que toda su vida ha tenido que sobrevivir a la adversidad por sus hijos y que este
                    tiempo de pandemia no es la excepción para ponerse creativa.</p>
                <p>“Yo nunca he recibido apoyo del gobierno, aquí no podemos quedarnos de brazos cruzados. Hay
                    bastantes madres solteras en mi comunidad, ayer estuve con dos de ellas que venden baleadas,
                    hojaldras, hay otras que lavan ropa ajena para ganar algo de dinero, y yo que me he estado ayudando
                    con la venta de mascarillas, siempre me encargan”, cuenta Marta haciendo un poco de tiempo mientras
                    costura en la sala de su casa el pedido más reciente de mascarillas de tela que confecciona.</p>


                <p>Marta trabajaba antes de la pandemia reparando ropa de segunda mano en una tienda en Tegucigalpa,
                    a 32 kilómetros de su comunidad. Ahora, sin poder salir, se las ha ingeniado para confeccionar
                    mascarillas y venderlas por pedido. En Honduras, el uso de mascarillas es obligatorio y las de tela son
                    aceptadas para uso preventivo.</p>
                <p>Marta cree que la ayuda de los gobiernos no es suficiente. En todo este tiempo de confinamiento la
                    alcaldía envió dos raciones de alimentos, cada una valorada en $15, las raciones del programa Honduras
                    Solidaria.</p>
                <p>Además, sostiene que las mujeres deben cuidarse entre ellas en las comunidades, y lo dice porque
                    Honduras es un país letal para las mujeres... solamente en tiempo de pandemia se registraron 26
                    femicidios según la base de datos del Centro de Derechos de Mujeres (CDM).</p>
                <p>“En esta comunidad hay varios hombres que han migrado y por eso las mujeres han quedado solas, pero
                    otras, casi la mayoría, hemos quedado solas porque hemos sobrevivido a la violencia doméstica. Como
                    mujeres nos tenemos que valorar y cuidar unas a otras, en mi caso yo tuve mi hija bien joven y me fue
                    mal con el papá de ellos, pero no hay que darnos por vencidas, a veces cree una que no va a poder pero
                    de una u otra manera se sale adelante, hay que esforzarse, salir a buscar el dinero honradamente, buscar
                    de qué trabajar, dios no desampara a nadie”, concluye.</p>
