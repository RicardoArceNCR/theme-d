                    <p>Alejandra tiene 32 años y una hija de 10. El padre de su hija vive en Estados Unidos así que la crianza
                        recae en ella pero es apoyada por varias mujeres de su familia: su hermana y su sobrina. Alejandra es
                        técnica en laboratorio clínico y antes de que la pandemia cambiara nuestras vidas, ella tenía una clínica
                        como negocio familiar donde era la encargada del laboratorio. Ahora está contratada temporalmente
                        para atender el laboratorio del Centro de Salud de Choloma, una ciudad en el norte de Honduras,
                        epicentro de la COVID-19.</p>
                    <p>“Donde trabajo hay personas infectadas entonces nos hacemos las pruebas seguido para estar seguros
                        de no habernos contagiado. Trabajamos sin los insumos adecuados, la Secretaría de Salud no nos está
                        proporcionando el equipo necesario, nos abastece semanalmente de mascarillas, batas y gorros. En lo
                        personal me he puesto en una posición positiva porque si me pongo con mucho miedo entonces se me
                        bajan las defensas, tengo mi familia y tengo que estar con el ánimo arriba”, cuenta.</p>

                    <p>Hace dos meses fue contratada por el gobierno en el marco de la emergencia, pero no le han pagado
                        su salario. La obligan a trabajar en alto riesgo al no brindarle los implementos de bioseguridad
                        diariamente en una zona de alto contagio por COVID-19.</p>
                    <p>La situación no es fácil para Alejandra, sobre todo porque el personal de salud <a href="https://contracorriente.red/2020/05/21/medicos-en-servicio-social-atienden-emergencia-en-la-calamidad/" title="Médicos en servicio social atienden emercia en calamidad" target="_blank" class="covid-tc1">ha sufrido hostigamiento
                        y discriminación</a> durante esta pandemia. <a href="https://cattrachas.org/" title="Red Lésbica Catrachas" target="_blank" class="covid-tc1">La Red Lésbica Cattrachas</a> presentó un informe que evidencia
                        que “el miedo a contagiarse de la enfermedad ha propiciado que grupos que no habían sido
                        discriminados, sean el nuevo foco del estigma. Pacientes de COVID-19, sus familiares y el personal de
                        salud han sufrido en las últimas semanas amenazas contra sus vidas, desalojos ilegales, ataques a su
                        integridad física y discriminación en la prestación de servicios, por ser considerados erróneamente
                        como ‘fuentes de contaminación’”.</p>
                    <p>Alejandra ha sido vista en la calle como portadora del virus solamente por llevar puesto su uniforme.
                        También ha sido discriminada porque en su familia dos personas resultaron infectadas.</p>
                    <p>“Necesitamos la solidaridad ahorita, la empatía. Mi hermano fue contagiado, los miembros del patronato
                        (organización vecinal) de su colonia se dieron cuenta, investigaron quién era y querían sacarlo de allí.
                        De dos formas he sentido la discriminación por el miedo de la gente que con la falta de conciencia e
                        información los hace actuar de tal forma”, relata Alejandra quien asegura buscar energía todos los días
                        para no sucumbir. </p>
                    <p>En Honduras no se habla de prevención más allá del uso de mascarillas, gel de alcohol o uso excesivo
                        de cloro. No se habla de la salud mental y de mantener fuerte el sistema inmunológico para vencer el
                        virus. Alejandra dice que en la medida de lo posible buscan comer saludable y mantenerse fuertes, a
                        pesar de solo contar con su salario mínimo y la poca ayuda del padre de su hija y lo que la familia apoya.
                        Ya vio a dos de sus familiares vencer el virus sin complicaciones.
                    </p>
                    <p>Además, una de las razones por las que Alejandra prioriza mantenerse activa y positiva es su hija, quien
                        padece un retraso moderado en el aprendizaje y rasgos de autismo.</p>
                    <p>“Esta condición de encierro la estresa mucho, no le exijo tanto, de mi trabajo voy a la casa a colaborar
                        con las tareas de ella, tengo en mi casa el apoyo de mi sobrina y una tía de la niña. Es una tarea bien
                        ardua venir, estar feliz y crear ideas para trabajar con ella, por eso en casa cantamos, bailamos, hacemos
                        karaoke, nos ponemos a hacer coreografías, a tratar de tocar instrumentos musicales. Todas esas
                        actividades nos fortalecen y nos mantienen tranquilas”, cuenta.</p>
                    <p>Hay una frase recurrente en las mujeres enfrentándose a esta pandemia: no nos podemos quedar de
                        brazos cruzados. Alejandra también lo dijo y como ellas, miles de mujeres en Honduras están en este
                        momento buscando opciones para vencer esta nueva adversidad.</p>
