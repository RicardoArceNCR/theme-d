                <p>Roxana Corrales es una mujer de 29 años que vive en una de las 12 comunidades de la península de
                    Zacate Grande en el Golfo de Fonseca, al sur de Honduras. Una comunidad rural, postergada y con
                    conflictos por la tierra. Según la base de datos del <a href="https://tierraderesistentes.com/es/index.php/datos/" title="Proyecto transnacional Tierra de Resistentes" target="_blank" class="covid-tc1">proyecto transnacional Tierra de Resistentes</a>, en los
                    últimos diez años en esta zona se registraron 50 ataques, entre acoso judicial y amenazas. Roxana es
                    parte de la única organización comunitaria que enfrenta esto, la Asociación de Defensa de Zacate
                    Grande (ADEPZA)</p>

                <p>Ahora con el encierro por la pandemia, ha tenido que organizarse para tomar sus clases virtuales y las
                    de su hija de 12 años. Roxana sigue estudiando en la universidad y cuando logra conectarse a internet
                    -si el servicio no falla y la energía eléctrica tampoco- se turnan las dos. “Apago el micrófono mientras
                    atiendo la clase y apoyo a la niña en la suya”, explica, mientras dice sentirse como una de las pocas
                    privilegiadas en su comunidad, muchas madres solteras no saben leer ni escribir y se les dificultaría
                    apoyar a sus hijos con las tareas o clases virtuales, aún teniendo un celular inteligente.</p>
                <p>Pero Roxana no solo tiene que sortear el vaivén del internet o la energía, sino sus múltiples trabajos
                    también. Una vez a la semana, los jueves por la tarde, Roxana se encarga de la programación de la radio
                    comunitaria donde informan las últimas noticias que ocurren en el país, una responsabilidad muy
                    grande en esta zona donde la radio es el único canal para enterarse de lo que sucede ya que muy poca
                    gente tiene acceso a internet. También trabaja en proyectos para ADEPZA y se involucra en la
                    organización comunitaria para la prevención de la COVID-19.</p>
                <p>En su comunidad no hay casos positivos aún, pero se han organizado para controlar la entrada y salida
                    de personas y la desinfección de las mismas. Esto también ha generado problemas en la comunidad,
                    cuenta Roxana.</p>
                <p>“Para quienes hemos sido más visibles en las comunidades por la lucha por la tierra es más difícil,
                    porque ya saben que vamos a ser nosotros vigilantes de que las cosas se hagan bien. En los cercos
                    epidemiológicos en la comunidad, por ejemplo, unos pocos deciden quién puede entrar y quién no y
                    tenemos que velar que se respeten los derechos de todas y todos”, relata Roxana. “Aquí se nos ha
                    acusado de querer que la gente se contagie porque una vez velamos por una mujer que regresó de
                    Tegucigalpa para estar con su niña en la cuarentena y no la dejaban entrar, nosotros estuvimos en
                    discusiones con el mismo alcalde y la policía y con la gente de la misma comunidad que cuidaba el paso,
                    porque le estaban violando el derecho a ella de estar con su hija, todo porque aquí se cree que quienes
                    vienen de Tegucigalpa están contagiados y eso genera estigma”, relata. </p>



                <p>Roxana lidia con esto a diario, pero también con el miedo.</p>
                <p>“El miedo hace lo suyo. A veces me pregunto si a mi hija le pega esta enfermedad, ¿qué voy a hacer? En
                    el centro de salud no hay tests, hay medidas de protección de rociar con cloro a quienes entran pero en
                    todo el municipio no hay lugar especializado ni personal capacitado para esto. Tendría que buscar un
                    vehículo para llevarla al hospital que está a una hora y media de aquí. El miedo hace su labor y una
                    sobredimensiona todo”, dice Roxana.
                </p>
