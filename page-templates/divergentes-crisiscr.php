                <h1 class="mb-5">Desempleo al doble</h1>
                <p>Así llegó Costa Rica a verse con un desempleo de 24% en agosto (el doble del año 2019), la mayor pobreza en casi 30 años (26% de la población), una proyección de contracción de la economía superior al 5% del PIB y un déficit fiscal que podría cerrar en este año por encima del 10% del total de la riqueza generada. Además, un endeudamiento total superior al 70% del PIB y constantes degradaciones en la nota que dan las agencias calificadoras de riesgo financiero al país. El riesgo de caer en el abismo económico es real y crece cada semana conforme se prolongan las tensiones políticas y sociales.</p>
                <p>Carlos Alvarado, que triunfó en las elecciones del 2018 marcadas por el ascenso de los partidos confesionales y la ratificación de la reconfiguración política del país, gobierno con solo diez diputados de su Partido Acción Ciudadana (PAC), una agrupación de origen de centro izquierda y progresista que él se ha visto en la necesidad de diluir para sumar apoyos ajenos en estos dos años y medio de gobierno. Ejerce su mandato frente a una Asamblea Legislativa dominada por fuerzas de oposición sin liderazgos ni líneas claras, lo que dificulta cualquier negociación política. </p>
                <p>La confianza en los partidos políticos no para de caer en las encuestas y alcanza también a gremios de empresarios, sindicatos y hasta las fuerzas religiosas que, además, padecen divisiones internas que reducen aún más las posibilidades de diálogos sociales sostenibles. El país de las decisiones civilizadas tiene rotos los canales de diálogo y abre espacios a voces alternativas.</p>
                <p>“Hay voces muy minoritarias, pero peligrosas que están llamando a generar inestabilidad. Jamás en Costa Rica prevalecerán”, dijo en un video Carlos Alvarado en uno de sus mensajes solemnes del mes de octubre, tras lamentarse por lo que considera son amenazas de la democracia. Cinco expresidentes de la República firmaron un manifiesto por el respeto a la institucionalidad y a las autoridades legítimas, así como un repudio a los actos de violencia “ajenos a la idiosincrasia costarricense”, en probable referencia a episodios como el intento de atropellar con un tractor a un grupo de policías, las vapuleadas a un grupo de ellos, el lanzamiento de una bomba casera sobre una patrulla o el ataque con un bate de béisbol contra un jefe policial frente a la sede de la Presidencia durante una protesta. Otro expresidente, José María Figueres (1994-1998) evitó firmar la carta y más bien señala la falta de planes contundentes del Gobierno para atender la urgencia económica.</p>
