                <p>“La situación actual del país y del régimen democrático es el resultado de la acumulación de problemas en tres grandes sistemas: el de representación formal, el sistema de ampliación de ciudadanía y el de distribución de la riqueza o de la pobreza (...) Viene de una trayectoria de al menos 25 años con la supeditación del interés público ante el mercado dominado por la banca y las finanzas transnacionales”, dijo el doctor en ciencias políticas Rotsay Rosales, coordinador del Observatorio de la Política Nacional (OPNA) en la Universidad de Costa Rica. También agrega el desgaste del sistema político, caducado el bipartidismo originado en mitad del siglo XX, ante los cambios sociales de las últimas tres décadas, con una alta fragmentación que no se empata con la dispersión de los nuevos partidos.</p>
                <p>“Tenemos todos los números de la rifa”, explicó de manera coloquial el politólogo Gustavo Araya, también de la UCR, al señalar también un mayor protagonismo de poderes fácticos contra el modelo de interés público y de posiciones contrarias a lo público que llevan incluso a actores privados, como el empresario Jenkins, a actuar en asuntos que el Estado no resuelve con prontitud.</p>
