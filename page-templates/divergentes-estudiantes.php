                <p>Amado Castilblanco saca de un cuarto un horno hecho con pedazos de zinc pintados de azul y blanco.
                    Fue el &uacute;ltimo que hizo su hijo Dodanim horas antes de que lo asesinaran el 30 de mayo de
                    2018.</p>
                <p>Dodanim, de 26 a&ntilde;os de edad, estudiaba tercer a&ntilde;o de Ingenier&iacute;a Agroindustrial
                    en la Universidad de Ingenier&iacute;a (UNI) de Estel&iacute;. El horno de zinc era un experimento
                    como parte de su carrera. &ldquo;&Eacute;l me ense&ntilde;&oacute; a hacerlos&rdquo;, dice Amado
                    Castilblanco, un se&ntilde;or de 73 a&ntilde;os de edad. &ldquo;Siempre me ense&ntilde;aba a hacer
                    cosas, as&iacute; era &eacute;l, era mi mejor amigo&rdquo;, agrega.</p>
                <p>Antes de las 12 del mediod&iacute;a del 30 de mayo de 2018, Dodanim contest&oacute; una llamada que
                    lo hizo salir de su casa. Se uni&oacute; a unos manifestantes que marcharon por las calles de Estel&iacute;
                    en solidaridad con las madres que les hab&iacute;an asesinado a sus hijos desde el 19 de abril de
                    2018, cuando estallaron las protestas en el pa&iacute;s. En la zona de la Direcci&oacute;n General
                    de Ingresos (DGI) la marcha fue atacada. Dodanim recibi&oacute; un disparo en el pecho. Muri&oacute;
                    horas despu&eacute;s en el hospital.</p>
                <p>Dodanim fue uno de 45 estudiantes asesinados por el r&eacute;gimen de Daniel Ortega y Rosario Murillo
                    durante los meses de abril y septiembre del a&ntilde;o 2018 en Nicaragua. Un an&aacute;lisis de
                    datos realizado por <strong>DIVERGENTES</strong> revela que los fallecidos eran alumnos de primaria,
                    secundaria, escuelas t&eacute;cnicas, universidades y un estudiante de postgrado. No v&aacute;ndalos
                    como proclam&oacute; el r&eacute;gimen.</p>

