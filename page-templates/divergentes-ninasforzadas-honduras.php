                        fueron remitidos a los juzgados fueron denunciados por el sector privado. En los casos del
                        sector p&uacute;blico &ldquo;no fue posible determinar con certeza si el personal hospitalario
                        promueve la acci&oacute;n de denuncia contra las mujeres por pol&iacute;ticas internas de su
                        lugar de trabajo o por motivos culturales personales&rdquo;.</p>
                    <p>&nbsp;El 50 % de los casos denunciados pertenec&iacute;an al Hospital Escuela Universitario y al
                        Materno infantil, ubicados en el mismo establecimiento en Tegucigalpa, mientras que un 35 %
                        fueron en el Hospital Regional de Atl&aacute;ntida y en el Mario Catarino Rivas, ubicados en la
                        zona norte del pa&iacute;s.</p>
                    <blockquote class="quote-card">
                        <p>
                            Maritza tuvo acompañamiento durante su aborto, tenía trabajo y su pareja compartió los
                            gastos: «fui de las excepciones de los miles de abortos que ocurren en este país donde por
                            eso se habla de mucho trauma, de mucho dolor porque son en condiciones tan indignas».
                        </p>

                    </blockquote>

                    <p>Ericka Garc&iacute;a recuerda que la penalizaci&oacute;n completa del aborto no s&oacute;lo
                        influye en embarazos no deseados sino que tambi&eacute;n puede quitarle la posibilidad a las
                        mujeres que si quieren ser madres, pero han tenido embarazos ect&oacute;picos, es decir que el
                        &oacute;vulo fecundado crece fuera del &uacute;tero, pues los ginec&oacute;logos y obstetras
                        tienen que esperar a que explote la trompa para proceder y al mismo tiempo extirpar todo o parte
                        del &uacute;tero, lo que impide que esa mujer pueda tener un embarazo despu&eacute;s.&nbsp;</p>
                    <p>La Sociedad de ginecolog&iacute;a y obstetricia se <a
                                href="https://somosmuchas.hn/wp-content/uploads/2021/01/pronunciamiento-SGOH.pdf">pronunci&oacute;
                            p&uacute;blicamente</a> cuando, a inicios del 2021, hubo un intento del Congreso Nacional
                        por convertir el aborto en un art&iacute;culo petreo, es decir, que solo pudiera modificarse con
                        una nueva Constituci&oacute;n. Sostuvieron que deben considerarse la aprobaci&oacute;n de
                        finalizaci&oacute;n del embarazo por tres causales: tras una agresi&oacute;n sexual, cuando el
                        feto es inviable y cuando la vida de la mujer corre peligro, &ldquo;hacemos un llamado a
                        respetar y escuchar las voces calificadas, que, con criterio cient&iacute;fico y bio&eacute;tico,
                        podemos contribuir en la reforma correcta y responsable de las leyes que involucran la salud de
                        las mujeres hondure&ntilde;as&rdquo;. Esa declaraci&oacute;n no fue escuchada. </p>

                    <h1 class="bukele-tc1 my-4 text-center">Un Congreso Nacional provida y de hombres</h1>
                    <p>En Honduras apenas 28 puestos de 128 en el Congreso Nacional pertenecen a mujeres diputadas. En
                        2020 ese congreso no aprob&oacute; ninguna legislaci&oacute;n en beneficio de las mujeres, ni
                        siquiera cuando las denuncias por violencia dom&eacute;stica se dispararon por la pandemia.
                        Aunque organizaciones esperaban desde hace dos a&ntilde;os la aprobaci&oacute;n de una Ley de
                        casas refugios para lograr que, finalmente, el Estado se hiciera responsable econ&oacute;micamente
                        de las 10 casas refugio, ninguna de origen estatal, con un monto anual de 20 millones de
                        lempiras.</p>
                    <p>Dos semanas despu&eacute;s de que se aprobara la interrupci&oacute;n del embarazo en Argentina,
                        el diputado hondure&ntilde;o Mario Perez, perteneciente al Partido Nacional, actualmente en el
                        Gobierno, present&oacute; un proyecto de ley que luego se denomin&oacute; &laquo;escudo contra
                        el aborto&raquo;, con la intenci&oacute;n de convertir los art&iacute;culos constitucionales que
                        penalizan el aborto, en art&iacute;culos p&eacute;treos que solo puedan modificarse v&iacute;a
                        una asamblea constitucional.&nbsp;</p>
                    <p>Finalmente, la reforma qued&oacute; en que ahora se necesitan 3/4 partes del Congreso Nacional
                        (96 de 128 votos) para poder modificar ese art&iacute;culo, cuando antes se necesitaban solo 86
                        votos. Sin embargo, la posibilidad de que esto sucediera ya era muy dif&iacute;cil, en 2017
                        cuando se discut&iacute;a un nuevo C&oacute;digo Penal se abri&oacute; la posibilidad de
                        despenalizar el aborto por tres causales: violaci&oacute;n sexual, inviabilidad del feto y
                        riesgo de vida para la madre. Solamente se lograron <a
                                href="https://www.facebook.com/congresonacionalhn/videos/1120690958376831">9 votos a
                            favor</a>.</p>
                    <p></p>
                    <p>En aquel entonces la diputada del partido Libertad y Refundaci&oacute;n, Scherly Arriaga, fue de
                        las &uacute;nicas que plante&oacute; por qu&eacute; deb&iacute;an considerar votar a favor.
                        &ldquo;La mayor&iacute;a en este congreso son hombres y van a venir a decidir por las mujeres (&hellip;)
                        estamos condenando a una mujer a que sea encarcelada no porque ella quiera tener un aborto, sino
                        porque no puede ser viable un nacimiento. No podemos continuar en un Estado est&aacute;tico
                        donde no hay cambios&rdquo;, dijo la legisladora. La diputada no hab&iacute;a terminado de
                        hablar cuando el presidente del Congreso Nacional, Mauricio Oliva, le silenci&oacute; el micr&oacute;fono.</p>
                    <p>Oliva es ahora precandidato a presidente por el Partido Nacional. Cuando present&oacute; su
                        informe anual sobre los logros en la legislaci&oacute;n nacional, recalc&oacute; con orgullo la
                        aprobaci&oacute;n de esta reforma: &ldquo;vamos hacia un nuevo paradigma conocido como el
                        transhumanismo universal donde la persona est&aacute; expuesta a incre&iacute;bles
                        modificaciones gen&eacute;ticas apuntalado por la tecnolog&iacute;a 5G, afectando el ADN humano
                        incluyendo sus valores donde la eutanasia y el aborto ser&iacute;an pr&aacute;cticas permitidas
                        y habituales&rdquo;, dijo.</p>
                    <h1 class="bukele-tc1 my-4 text-center">Una discusión poco transparente </h1>
                    <p>La sesi&oacute;n del Congreso Nacional en la que se aprob&oacute; esta reforma, al igual que
                        todas las sesiones, inici&oacute; con una oraci&oacute;n religiosa. Estas sesiones se siguen
                        realizando de manera virtual en Honduras. Para Ericka Garc&iacute;a la plataforma en la que se
                        discuten las leyes actualmente no es transparente: &laquo;ni sab&iacute;an quienes votaban ni se
                        pod&iacute;a tener acceso a saber qu&eacute; votos se daban, no hab&iacute;a nadie viendo cu&aacute;ntos
                        votos fueron y no es que pensemos que mucha gente vot&oacute; en contra&raquo;.</p>
                    <p>La realidad es que, aunque esta reforma obtuvo 28 votos en contra, los 5 de los 6 que votaron p&uacute;blicamente
                        en oposici&oacute;n y tuvieron espacio de dar sus argumentos. Aseguraron que no estaban a favor
                        por considerar que se trataba de un distractor, pero que se consideraban provida y eso deb&iacute;a
                        de quedar claro. El diputado Lenin Rodas, del partido Unificaci&oacute;n Democr&aacute;tica (UD)
                        fue el &uacute;nico que se pronunci&oacute; a favor de la interrupci&oacute;n del embarazo, dijo
                        que lo hac&iacute;a en nombre de su hija. <a
                                href="https://www.facebook.com/congresonacionalhn/videos/1120690958376831">Ese espacio
                            de debate se abri&oacute;</a> para escuchar a 20 hombres y apenas 9 mujeres.</p>
                    <p>Mientras tanto, el m&eacute;dico Denis Castro Bobadilla, del partido Alianza Patri&oacute;tica,
                        aunque se proclam&oacute; provida, dijo que en un tema tan controversial se le deber&iacute;a
                        consultar a la poblaci&oacute;n a trav&eacute;s de un refer&eacute;ndum. &ldquo;Hay que
                        consultar a las mujeres por las cosas que han pasado. Conozco casos de m&eacute;dicos, abogados,
                        periodistas, militares que violaron a sus hijas (&hellip;). Estamos a favor de la vida, por
                        supuesto, pero ninguna ley de Honduras va a poder impedir un aborto espont&aacute;neo o un
                        embarazo ect&oacute;pico&rdquo;, propuso.</p>
                    <p>Mientras que la diputada del Partido Innovaci&oacute;n y Unidad (PINU), Doris Guti&eacute;rrez
                        denunci&oacute; que la socializaci&oacute;n fue subjetiva y desigual. &ldquo;A grupos a favor
                        del proyecto se les llev&oacute; a un hotel, fue presencial, fue transmitida por todos los
                        medios incluyendo al canal del Congreso Nacional y cuando se convoc&oacute; a las organizaciones
                        de mujeres ni siquiera el canal transmiti&oacute; esa reuni&oacute;n&rdquo;, se&ntilde;al&oacute;.</p>
                    <p>Durante el proceso de socializaci&oacute;n de ese proyecto hubo una reuni&oacute;n donde se
                        escuch&oacute; a los representantes de iglesias, as&iacute; como al Comit&eacute; Provida en
                        Honduras: &ldquo;No hay que lanzar a las mujeres a un &lsquo;abortorio&rsquo; para que quede
                        sola con el fantasma de su hijo que la va a perseguir para siempre, esa es la experiencia que yo
                        tengo en nuestro trabajo provida, esas mujeres lloran a escondidas siempre y las que no quieren
                        que las otras hagan lo mismo&rdquo;, dijo Martha Lorena Casco, representante de provida
                        Honduras, durante la <a
                                href="https://www.facebook.com/congresonacionalhn/videos/901096714024391">socializaci&oacute;n</a>.
                    </p>
                    <p>Casco fue diputada en el Congreso Nacional durante 2009, en abril de ese a&ntilde;o intent&oacute;
                        aprobar un decreto para prohibir la pastilla anticonceptiva de emergencia (PAE) porque eran
                        &laquo;un aborto farmacol&oacute;gico&raquo; y las tomaban &laquo;ni&ntilde;as de 12 a 16 a&ntilde;os
                        despu&eacute;s de una noche de parranda&raquo;. Este decreto fue respaldado por un dictamen
                        emitido por el presidente del Colegio M&eacute;dico de ese entonces: Mario No&eacute;
                        Villafranca.</p>
                    <p>El presidente en aquel momento, Manuel Zelaya Rosales, vet&oacute; ese decreto argumentando que
                        aprobarlo violentaba convenios internacionales. Sin embargo, durante el Gobierno de facto de
                        Micheletti Ba&iacute;n, Mario No&eacute; Villafranca fue nombrado ministro de salud y en su
                        posici&oacute;n firm&oacute; un acuerdo ministerial emitido el 21 de octubre de 2009, en el que
                        se prohibi&oacute; la venta, el uso, consumo y distribuci&oacute;n de los anticonceptivos de
                        emergencia.</p>
