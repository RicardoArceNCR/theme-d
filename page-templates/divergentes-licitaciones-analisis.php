                <h1 class="indigenas-title wow animate__animated animate__fadeIn mb-5"><span>Un vacío legal</span> que da cabida a la corrupción</h1>
                <p>Aunque las contrataciones simplificadas son amparadas por un vacío de ley que nos las regula totalmente, el experto municipal Gilberto Lindo alerta que este esquema irregular da cabida a la corrupción, una práctica que sí está penada en Nicaragua.</p>
                <p>“Es un proceso ilegal porque están simulando situaciones de urgencia para aplicar un procedimiento y poder contratar a quienes ellos quieran, a quienes les dé la gana... No hay control sobre eso. Esta es una salida a la corrupción. Y este es un modelo que se repite en todos los municipios de corte oficialista”, afirma Lindo, quien lleva años analizando presupuestos y gestión municipal en Nicaragua.</p>
                <p>La Ley 801, en el acápite que se refiere a la Contratación Simplificada, justifica las adjudicaciones bajo esta vía cuando se trata de distribución de víveres, contratación de artistas o de servicios técnicos a profesionales especializados para un área organizativa de la municipalidad. Por ejemplo los arrendamientos, compra de bienes inmuebles o alquiler del mismo, o cuando exista un proveedor único en el mercado, algo que es raro. </p>
                <p>También cuando existen emergencias o alguna situación de calamidad pública. Por ejemplo, si ocurre una catástrofe la contratación simplificada agiliza el proceso para resolver la eventualidad. Sin embargo, luego de haber resuelto el problema, la alcaldía debe aprobar el gasto e informar detalladamente todo el proceso.</p>
                <p>“Pero hay una segunda modalidad que dice que pueden contratar en situaciones de emergencias o urgentes que <b>no se derivan de desastres o calamidad pública</b>. Esa es una expresión que la ley ahí tiene abierta. Eso le da paso a ellos para ir por esa vía, pero claro, hay restricciones. La misma ley dice, un poquito más adelante, que antes de tomar esta decisión, tenés que hacer un documento en el que justifiqués de manera razonada por qué estás definiendo este mecanismo”, explica Lindo.</p>
                <p>El municipalista advierte que, si bien la ley pone un límite para evitar que ocurran contrataciones irregulares, las autoridades municipales no respetan el mismo y violan los causales que la misma ordenanza establece.</p>
                <p>“Se supone que son obras que salieron de repente y que no podía esperar todo el proceso que conlleva llamar a reunión al consejo municipal, hacer una reunión de consejo, aprobar el gasto, discutir si el proyecto es viable, si es aceptable… como no pueden hacer todo eso. Entonces es una obra que apareció y hay que responder urgentemente”, plantea Lindo</p>
                <p>La ley también aclara que una vez se haya realizado la contratación de urgencia no derivada de una calamidad, la autoridad municipal debe remitir los expedientes con sus soportes a la Contraloría de la República quince días después de haber suscrito un contrato.</p>
