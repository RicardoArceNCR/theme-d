                <span> “Operación limpieza”</span></h1>
            <p>&ldquo;M&eacute;tanse a las casas&rdquo; y &ldquo;no graben o les disparamos&rdquo;, son las dos
                advertencias &mdash;o amenazas&mdash; que recibe Juan*. Se las grita un hombre encapuchado y con fusil
                de asalto AK-47 en mano que acaba de irrumpir la tranquilidad del barrio Mar&iacute;a Auxiliadora junto
                a un nutrido grupo que igual lleva la cara tapada. Cierra la puerta para no recibir un balazo, pero
                fisgonea por la rendija: ve que todos avanzan con t&eacute;cnica militar hacia las barricadas y disparan
                sus armas sin respiro. A matar.</p>
            <p>Lo anterior es de las primeras escenas del ataque lanzado a los barrios orientales de Managua el 11 de
                junio de 2018, todo porque un d&iacute;a antes levantaron barricadas. Tambi&eacute;n el estreno de la
                &ldquo;Operaci&oacute;n Limpieza&rdquo; del r&eacute;gimen de Daniel Ortega, ejecutada por los
                encapuchados &mdash;llamados paramilitares por la ciudadan&iacute;a&mdash; y fuerzas policiales, que m&aacute;s
                adelante dejar&iacute;a una estela de muerte, encarcelados y arrojar&iacute;a miles al exilio.</p>
            <p>Juan recuerda que estas barricadas se levantaron en el Mar&iacute;a Auxiliadora, Ducual&iacute;,
                Larreynaga y El Paraisito para protegerse de los ataques nocturnos de las &ldquo;caravanas de la muerte&rdquo;,
                conformadas por los mismos encapuchados. Lo hicieron porque el domingo 10 de junio hab&iacute;an probado
                el amargo sabor de su violencia: fue asesinado un vecino de 39 a&ntilde;os mientras circulaba en su moto
                por el barrio Venezuela. Un disparo en la cabeza le apag&oacute; el mundo para siempre.</p>
            <p>La poblaci&oacute;n alzada intent&oacute; evitar que se quitaran las barricadas, pero no pudo. Los que
                estaban tras ellas se mantuvieron en pie de lucha durante m&aacute;s de tres horas, pero al final la
                resistencia cay&oacute; porque consisti&oacute; en defenderse con piedras y morteros, mientras del otro
                bando sobraban las pistolas y AK-47. De acuerdo con testigos oculares, la operaci&oacute;n fue liderada
                por los paramilitares. Eran los que daban las &oacute;rdenes de c&oacute;mo se ten&iacute;a que mover el
                resto.</p>
            <p>Detr&aacute;s de los encapuchados iban j&oacute;venes con armas hechizas, palos y tubos, quienes tambi&eacute;n
                amenazaban a cualquier cristiano que miraban asom&aacute;ndose tras puertas y ventanas. &ldquo;M&eacute;tase
                vieja antes que la descachimbemos&rdquo;, advert&iacute;an. &ldquo;Eran vagos tra&iacute;dos de otros
                barrios que no ten&iacute;an la t&eacute;cnica demostrada por los encapuchados&rdquo;, asegura Juan.</p>
            <p>Cuando el &aacute;rea fue asegurada por los civiles armados, entraron los polic&iacute;as y se
                mantuvieron en la zona hasta que los adoquines ocupados como barricadas fueron levantados por una pala
                mec&aacute;nica y montados en camiones de la Alcald&iacute;a de Managua.</p>
            <p>&ldquo;No quer&iacute;an que ni grab&aacute;ramos cuando entraban los camiones de la Alcald&iacute;a a
                levantar los adoquines. Desde el muro de mi casa saqu&eacute; el celular y uno de ellos vio, le avis&oacute;
                a los dem&aacute;s y me agarraron a pedradas y morterazos la casa&rdquo;, cuenta otro habitante, quien
                omite brindar su nombre porque teme por su vida.</p>
            <p>La municipalidad de Managua, la m&aacute;s grande del pa&iacute;s y actualmente en poder de una
                administraci&oacute;n orteguista, decenas de veces qued&oacute; retratada de c&oacute;mplice en la
                Operaci&oacute;n Limpieza de Ortega al destinar maquinaria y personal para este tipo de trabajos. Para
                camuflar su participaci&oacute;n mand&oacute; a tapar el logo de la instituci&oacute;n, estampado en las
                puertas de los camiones.</p>
            <p>Pese a ser violenta, esa jornada en los barrios orientales termin&oacute; sin contarse personas
                asesinadas. Los pobladores de los alrededores lo acu&ntilde;an a que se pudo escapar a tiempo porque se
                disparaba a matar. No hubo disparos al aire en se&ntilde;al de advertencia, sino hacia las barricadas.
                De esto hay constancia en videos grabados por varios pobladores arriesg&aacute;ndose a ser vistos y no
                quedar para contar el cuento.</p>
            <p>El estallido social inici&oacute; el 18 de abril de 2018 y en menos de una semana el pa&iacute;s estaba
                sumido en un cap&iacute;tulo de protestas sin precedentes durante los a&ntilde;os de Ortega en el poder
                por segunda vez, que inici&oacute; en 2007 &mdash;antes estuvo entre 1979 y 1989. Unas reformas
                unilaterales al Seguro Social encendieron la llama c&iacute;vica con plantones en la ciudad de Le&oacute;n
                y en Managua. En la capital las primeras manifestaciones se registraron en los sectores de Camino de
                Oriente y la Universidad Centroamericana (UCA).</p>
            <p>En los tres puntos la respuesta fue la represi&oacute;n. Sin embargo, la ciudadan&iacute;a no recul&oacute;.
                En esa l&oacute;gica de manifestaci&oacute;n leg&iacute;tima, donde se sumaron otros sectores, es que
                empezaron a levantar barricadas en diferentes puntos de la capital y trancar las carreteras principales
                del pa&iacute;s.</p>
            <p>El ataque a los barrios orientales se constituy&oacute; como el primero de la denominada &ldquo;Operaci&oacute;n
                limpieza&rdquo;, que consisti&oacute; en disolver las protestas y abrir el paso de forma violenta, con
                balas. Ese 11 de junio nadie se imagin&oacute; que solo era un ensayo de lo que vendr&iacute;a semanas
                despu&eacute;s, resumido en tres palabras: horror, muerte y luto.</p>
