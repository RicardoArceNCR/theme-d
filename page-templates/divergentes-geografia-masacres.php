                cruzaron a suelo costarricense para solicitar refugio al Gobierno. &ldquo;Ac&aacute; no estamos bien,
                pero si volvemos nos meten presos o nos matan&rdquo;, reconoce otro carace&ntilde;o exiliado en Costa
                Rica y que constantemente recibe amenazas desde Nicaragua por mensajes de texto y notas de audio.</p>
