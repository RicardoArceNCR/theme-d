                julio. Joao Maldonado, uno de los entrevistados y actualmente exiliado en Costa Rica, explica que en
                avanzada se movilizaba un grupo de civiles, con pasamonta&ntilde;as y de contextura recia. Su movimiento
                era desordenado, a veces torpe, usaban AK-47 en su mayor&iacute;a y se escudaban detr&aacute;s de las
                camionetas en que llegaron. Luego le segu&iacute;a otro comando que cargaba el armamento pesado y su
                despliegue era con t&eacute;cnica. &ldquo;Demostraban mayor preparaci&oacute;n, t&aacute;ctica y con f&iacute;sico
                que se pod&iacute;a pensar que hab&iacute;an sido sometidos a ejercicios&rdquo;, dice Maldonado.</p>
            <p>Una vez que la zona era asegurada, entraba el contingente policial y palas mec&aacute;nicas de la Alcald&iacute;a
                para tumbar las barricadas y as&iacute; avanzar hasta el coraz&oacute;n de cada ciudad, siendo Jinotepe
                la &uacute;ltima en caer. Todos los frentes de ataque se coordinaban por radios comunicadores.</p>
            <p>Cuando las tres ciudades cayeron en control de los encapuchados, quienes lograron capear la lluvia de
