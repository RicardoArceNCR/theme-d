                    <p>El Salvador, uno de los 16 pa&iacute;ses en el mundo, a la par de Iraq, el Congo y Egipto, que
                        tienen la penalizaci&oacute;n absoluta del aborto. Es la naci&oacute;n centroamericana con las
                        leyes m&aacute;s severas para mujeres que sufrieron emergencias obst&eacute;tricas.</p>
                    <p>&ldquo;La criminalizaci&oacute;n por aborto es un problema de salud p&uacute;blica y de justicia
                        social que se traduce en discriminaci&oacute;n e injusticia contra las mujeres m&aacute;s
                        vulneradas, con menos oportunidades de acceder a servicios seguros de salud y con m&aacute;s
                        posibilidades de ser encarceladas, extorsionadas, chantajeadas, manipuladas, etc&rdquo;, apunta
                        Ipas Cam.</p>
                    <p>Desde 1998 a 2019, 181 mujeres fueron procesadas por aborto o por homicidio agravado, con penas
                        de hasta 40 a&ntilde;os de prisi&oacute;n, seg&uacute;n la investigaci&oacute;n Del Hospital a
                        la C&aacute;rcel, de la Agrupaci&oacute;n.</p>
                    <p>Hay 20 madres en prisi&oacute;n en la actualidad: 15 tienen condena firme y 5 tienen un proceso
                        activo porque a&uacute;n no han enfrentado juicio, seg&uacute;n los registros de la Agrupaci&oacute;n,
                        que desde su fundaci&oacute;n en 2009 ha logrado la libertad de 45 mujeres.</p>
                    <p>&ldquo;A nivel mundial El Salvador se conoce por dos cosas: por toda la criminalidad de las
                        pandillas y por la criminalizaci&oacute;n de las mujeres por aborto. El primero requiere una
                        soluci&oacute;n compleja. El segundo requiere voluntad pol&iacute;tica de los actores, y eso es
                        lo que ha faltado&rdquo;, se&ntilde;ala Morena Herrera, presidenta de la Agrupaci&oacute;n, y un
                        referente del tema en El Salvador.</p>
                    <p>En 2016 lleg&oacute; a la Asamblea Legislativa la propuesta de despenalizar el aborto en algunas
                        circunstancias: cuando corre peligro la vida de la madre, o cuando el embarazo sea producto de
                        una violaci&oacute;n, por ejemplo. Pero esa iniciativa, pese al cabildeo de la sociedad civil,
                        no prosper&oacute;. El partido m&aacute;s progresista, el FMLN, que en aquel momento era partido
                        de Gobierno, desperdici&oacute; la oportunidad de dar un acompa&ntilde;amiento m&aacute;s
                        robusto, a juicio de las integrantes de la Agrupaci&oacute;n.</p>
                    <p>&ldquo;Esta lucha por la despenalizaci&oacute;n del aborto todav&iacute;a no es un componente
                        crucial en la agenda de ning&uacute;n partido&rdquo;, advierte Sara Garc&iacute;a Gross.</p>
