                <p>Sin posibilidad de acudir a un ejército para obligar a atender las medidas sanitarias o a instrumentos legales del ámbito militar como el toque de queda, Costa Rica echa mano de sus instituciones y de inversiones hechas en el pasado relacionadas con recursos que no debieron utilizarse para mantener fuerzas armadas o los costos que habrían implicado sus operaciones en episodios como las guerras centroamericanas de los años 80, por ejemplo.</p>
                <h1 class="mb-4 text-left">Entramado civilista </h1>
                <p>Adicionalmente se desarrolló en Costa Rica la apuesta por un sistema de Derecho interno e internacional, un entramado civilista y por el mecanismo electoral como método único de relevo del poder político, sin posibilidad de golpes militares después de 1948. Eso a su vez redunda en la depuración del funcionamiento institucional democrático, como en la división moderada de los poderes de la República y la necesidad de un poder electoral que reduzca al mínimo los espacios de sospecha.</p>
                <p>Fue en 1948 cuando un intento de alteración electoral derivó en enfrentamientos políticos y en la revolución que tornó en una guerra civil ganada por las fuerzas lideradas por Figueres, quien después, durante año y medio ejerció como jefe de un gobierno de facto en medio de tensiones. </p>
                <p>Era una época en que Estados Unidos ejercía dominio sobre los ejércitos de Nicaragua y Panamá, al norte y sur de Costa Rica, dada la importancia que en la primera mitad del siglo XX adquirió la región cercana al canal de Panamá. Esto facilitaba las cosas para Figueres, según la historiadora Mercedes Muñoz, porque Costa Rica podía que valerse de los acuerdos de seguridad colectiva para efectos internacionales, mientras que el poder interno de las fuerzas armadas había sufrido un menoscabo económico progresivo en la primera mitad del siglo XX y un golpe letal durante la revolución del 48.</p>
                <p>La abolición formalizada en 1949 no fue producto de una iluminación repentina. El mismo Figueres dijo que desde 1919 hubo propuestas abolicionistas, después de caída la dictadura del general Federico Tinoco que había empezado con un golpe militar en 1917. Incidieron factores como la crisis económica mundial de los años 30 y la relativa debilidad de las clases militares ligadas a élites económicas menos poderosas que en el resto de Centroamérica, pero las circunstancias nunca fueron suficientes hasta que Figueres concluyó  que era una amenaza para su gobierno la existencia formal de la institución del ejército.</p>
