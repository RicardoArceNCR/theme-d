                <p><b>SAN JOSÉ, COSTA RICA</b>–. En mayo de este año, en plena pandemia de COVID-19, la reconocida líder ambientalista Christiana Figueres fue la invitada especial en el acto de formalización del primero de diciembre como fiesta nacional en Costa Rica por la abolición del Ejército. Siete décadas después, la formalidad costarricense aún digiere el significado de aquella decisión que se tomó con fines más políticos que pacifistas, pero que se convirtió en una insignia internacional. Sobre todo, en un símbolo de estilo de desarrollo y una rareza en Centroamérica, una región marcada con sangre por sus ejércitos. </p>
                <p>“La decisión de abolir el ejército fue un valiente rompimiento con el status quo que teníamos y que ya había agotado su beneficio”, resumió Figueres, hija del político que en 1949 formalizó la abolición del Ejército y que encauzó al país por una ruta de desarrollo que depararía altos niveles de estabilidad política y progreso social, aunque poco de esto podía presupuestarse a mitad de siglo.</p>
                <p>Costa Rica es ahora el país más estable de Centroamérica y una de las democracias más consolidadas del continente americano, con un sistema de bienestar social y un entramado institucional que predomina por encima de los anhelos y antojos de los gobernantes del momento. Las explicaciones pueden ser variadas y depender de la lente ideológica, pero pocos factores generan tanto consenso como los beneficios de la decisión de José Figueres de abolir aquel ejército que le representaba más un lastre que un activo. Y al país, se pudo concluir tiempo después.</p>
                <p>Ahora se tiene claro, aunque requirió décadas en formarse una comprensión general sobre el valor de la abolición del ejército, en buena medida porque esta se identificó con el Partido Liberación Nacional (PLN) fundado por Figueres, lo cual dificultaba que se le aplaudiera desde el partido adversario durante el bipartidismo del siglo XX. En el siglo actual, diluida mucha de la militancia y las adversidades partidarias del pasado, la ausencia de ejército es una de las banderas nacionales, aunque no fue hasta este 2020 cuando se aprobó como fiesta nacional el 1 de diciembre.</p>

                <h1 class="mb-4 text-left">Más allá de la imágen, los beneficios palpables </h1>
                <p>Las consecuencias, sin embargo, resultaron en enormes beneficios más allá de la imagen de paz y la proyección de ser un país que supo trascender a la expresión militar del poder instalada como una norma mundial. Esos réditos se conocen con números: la inversión social se multiplicó por cinco al pasar de 2,6% del PIB pasó al 13,4% en los 25 años posteriores a la supresión del ejército, como un efecto atribuible a la decisión que materializó Figueres.</p>
                <p>En ese cuarto de siglo posterior a la desmilitarización, Costa Rica duplicó  la inversión en educación y triplicó la cantidad de escuelas (2.610 en el año 1974, una por cada 800 habitantes del momento). También pudo aumentar a 29% del PIB el presupuesto destinado salud y multiplicar por tres la cobertura de seguro social de la población, según las conclusiones de un estudio publicado en 2018 en la Universidad de Costa Rica por los investigadores Alejandro Abarca y Suráyabi Ramírez.</p>
