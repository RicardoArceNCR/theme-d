                <p>Casi 50 años después, en el contexto de la pandemia de COVID-19, cobrarían valor esas inversiones. Costa Rica recibió el virus global con un sistema de salud sólido y un entramado social que, aunque deteriorado en las últimas tres décadas, funcionó como soporte de las acciones políticas e institucionales para el control sanitario, al menos en la primera etapa pandémica.
