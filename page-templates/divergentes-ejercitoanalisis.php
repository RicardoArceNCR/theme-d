                <p><b>SAN JOSÉ, COSTA RICA</b>–. Las fuerzas armadas fueron actores protagonistas de la política centroamericana al menos hasta mediados de los 90, cuando finalizaron los conflictos militares que asolaron a la región durante las últimas décadas del siglo XX. Treinta años después, aunque ya no ocupan la primera línea de la política, los militares sobreviven como grupos con una gran capacidad de presión y muy activos en la vida cotidiana de los países centroamericanos, a excepción de Costa Rica y Panamá, las únicas dos naciones que actualmente no tienen fuerzas armadas. Su poder ha cambiado de forma, pero no se ha extinguido y persiste bajo nuevos ropajes.</p>
                <p>¿Qué explica su permanencia y su poder? Con la excepción de Costa Rica, en el resto de Centroamérica los aparatos militares cerraron el siglo XX y entraron al nuevo siglo con una baja legitimidad y fuerzas de policía prácticamente inexistentes o muy débiles. Del otro lado, las recién estrenadas autoridades civiles contaban con poca experiencia democrática y tenían que lidiar con una región donde la inseguridad y la violencia permanecen como el problema más importante para las sociedades. La solución siempre fue adoptar políticas de seguridad de mano dura que dieron preponderancia a las fuerzas militares.</p>
                <p>Esa compleja relación entre fuerzas armadas, liderazgos políticos civiles y necesidades ciudadanas ha tenido varios momentos en Centroamérica. En la década de los 90 del siglo XX, cuando finalizaron los conflictos bélicos, la principal preocupación era la subordinación de las fuerzas armadas a las autoridades civiles recién constituidas y la separación de las funciones militares y policiales.</p>
                <p>En la primera década del siglo XXI, los militares centroamericanos se enfocaron en realizar sus propios procesos de modernización, reconversión y profesionalización, como se les llamó en casi todos los países; se redimensionaron sus fuerzas y presupuestos. En la reinvención, encontraron nuevas rutas para mantenerse en los esquemas de poder que se estaban reconfigurando en todos los países de la región a través de nuevas formas. Así, los ejércitos comenzaron a participar en las llamadas misiones no tradicionales como la prevención de desastres, la asistencia humanitaria, el combate al narcotráfico y la protección de recursos naturales; además, comenzaron a realizar tareas de seguridad ciudadana, invadiendo campos de acción civil, y crearon espacios de coordinación y acción conjunta regional. En esa época también crecieron las empresas de seguridad privadas manejadas por los militares, el comercio de armas y municiones, y las empresas privadas en sectores clave de la economía con participación de militares como socios. La década cerró con el golpe militar que derrocó a Manuel Zelaya, el presidente de Honduras, marcando un punto de inflexión política en la región y revelando que los ejércitos no habían abandonado su poder ni su protagonismo.</p>
